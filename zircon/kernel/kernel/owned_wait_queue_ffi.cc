// Keep in sync with the Rust `BAAOLockingDetails` in owned_wait_queue.rs.
static_assert(sizeof(OwnedWaitQueue::BAAOLockingDetails) == 16);
static_assert(alignof(OwnedWaitQueue::BAAOLockingDetails) == 8);
static_assert(offsetof(OwnedWaitQueue::BAAOLockingDetails, new_owner) == 0);
static_assert(offsetof(OwnedWaitQueue::BAAOLockingDetails, stop_point) == 8);

// Keep in sync with the Rust `WakeOption` in owned_wait_queue.rs.
static_assert(static_cast<uint32_t>(OwnedWaitQueue::WakeOption::None) == 0);
static_assert(static_cast<uint32_t>(OwnedWaitQueue::WakeOption::AssignOwner) == 1);
static_assert(sizeof(OwnedWaitQueue::WakeOption) == sizeof(uint32_t));

namespace {

class RustWakeRequeueHook final : public OwnedWaitQueue::IWakeRequeueHook {
 public:
  using AllowFn = bool (*)(void* ctx, const Thread* t);
  using OnWakeOrRequeueFn = void (*)(void* ctx, Thread* t);

  RustWakeRequeueHook(AllowFn allow_fn, OnWakeOrRequeueFn on_wake_or_requeue_fn, void* ctx)
      : allow_fn_(allow_fn), on_wake_or_requeue_fn_(on_wake_or_requeue_fn), ctx_(ctx) {}

  bool Allow(const Thread& t) override { return allow_fn_(ctx_, &t); }
  void OnWakeOrRequeue(Thread& t) override { on_wake_or_requeue_fn_(ctx_, &t); }

 private:
  AllowFn allow_fn_;
  OnWakeOrRequeueFn on_wake_or_requeue_fn_;
  void* ctx_;
};

}  // namespace

