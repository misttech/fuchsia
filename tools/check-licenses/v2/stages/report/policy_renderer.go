package report

import (
	"context"
	"fmt"

	"go.fuchsia.dev/fuchsia/tools/check-licenses/v2/config"
	"go.fuchsia.dev/fuchsia/tools/check-licenses/v2/pipeline"
)

// PolicyRenderer is a Stage 6 renderer that generates JSON configuration files
// for policy compliance exceptions.
type PolicyRenderer struct {
	Config *config.MasterConfig
}

// NewPolicyRenderer creates a new PolicyRenderer.
func NewPolicyRenderer(cfg *config.MasterConfig) *PolicyRenderer {
	return &PolicyRenderer{
		Config: cfg,
	}
}

func (r *PolicyRenderer) Run(ctx context.Context, projects []*pipeline.Project, errors []pipeline.ComplianceError) error {
	for _, e := range errors {
		switch e.CheckName {
		case config.PolicyCheckAllProjectsMustHaveALicense:
			fmt.Printf(" [Policy] Processing missing license: %s\n", e.Project)
			_, _ = r.Config.AddPolicyException(e.CheckName, e.Project, "TODO: Auto-generated by fx check-licenses fix", "Auto-generated exception via fix")

		case config.PolicyCheckAllLicenseTextsMustBeRecognized:
			fmt.Printf(" [Policy] Processing unrecognized license: %s\n", e.FilePath)
			_, _ = r.Config.AddPolicyException(e.CheckName, e.FilePath, "TODO: Auto-generated by fx check-licenses fix", "Auto-generated exception via fix")
		}
	}
	return nil
}
