set -euo pipefail

echo 'Updating goldens...'

if ! fx go test ./tools/integration/testsharder/cmd -update-goldens; then
	echo 'If this failure is unexpected, try running `fx setup-go` and retry.'
	exit 1
fi

# The test deletes all goldens before regenerating them, so the files left in
# testdata are exactly the goldens of the current test cases. Bazel can't
# discover test inputs at build time, so write them to a checked-in list that
# BUILD.bazel loads rather than having people maintain the list by hand.
testsharder_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
{
	cat <<'HEADER'
# Copyright 2026 The Fuchsia Authors. All rights reserved.
# Use of this source code is governed by a BSD-style license that can be
# found in the LICENSE file.

"""Golden files read by testsharder_tests.

Generated by update_goldens.sh. Do not edit by hand.
"""

GOLDENS = [
HEADER
	(cd "${testsharder_dir}" && LC_ALL=C ls cmd/testdata/*.golden.json) |
		sed 's/.*/    "&",/'
	echo ']'
} >"${testsharder_dir}/goldens.bzl"
