/// Verify the given code depending on the type of the parameters and the registered external
/// functions. Returned `VerifiedEbpfProgram` should be linked in order to execute it.
pub fn verify_program(
    code: Vec<EbpfInstruction>,
    calling_context: CallingContext,
    logger: &mut dyn VerifierLogger,
) -> Result<VerifiedEbpfProgram, VerifierError> {
    if code.len() > BPF_MAX_INSTS {
        return error_and_log(
            logger,
            VerifierError { kind: VerifierErrorKind::ProgramTooLarge, pc: None },
        );
    }
    // Pre-scan the program to ensure all LDDW instructions are structurally well-formed,
    // even if they are in unreachable code. This is necessary because:
    // 1. The linker may rewrite LDDW instructions (e.g., to resolve map pointers) and
    //    expects them to be well-formed.
    // 2. It ensures that the second part of every LDDW has a `code` of 0 (invalid opcode).
    //    This guarantees that any attempt to jump directly into the second part of an
    //    LDDW will be rejected during verification as an invalid instruction.
    //
    // It also computes the prune points: the targets of the jumps and the instructions following
    // a conditional jump or a `cmpxchg` (which also branches into two states). Every loop and
    // every join of two branches goes through one of them, and the states are only compared with
    // and recorded as terminating contexts at these points.
    let mut terminating_contexts: Vec<Option<TerminatingContexts>> =
        (0..code.len()).map(|_| None).collect();
    let mut scan_pc = 0;
    while scan_pc < code.len() {
        let inst = &code[scan_pc];
        if inst.code() == BPF_LDDW {
            let Some(next_instruction) = code.get(scan_pc + 1) else {
                return error_and_log(
                    logger,
                    VerifierError { kind: VerifierErrorKind::IncompleteLddw, pc: Some(scan_pc) },
                );
            };
            if next_instruction.code() != 0
                || next_instruction.offset() != 0
                || next_instruction.src_reg() != 0
                || next_instruction.dst_reg() != 0
            {
                return error_and_log(
                    logger,
                    VerifierError { kind: VerifierErrorKind::MalformedLddw, pc: Some(scan_pc) },
                );
            }
            scan_pc += 2;
        } else {
            let class = inst.code() & BPF_CLS_MASK;
            let op = inst.code() & BPF_SUB_OP_MASK;
            let is_cmpxchg = (inst.code() == (BPF_STX | BPF_ATOMIC | BPF_W)
                || inst.code() == (BPF_STX | BPF_ATOMIC | BPF_DW))
                && inst.imm() as u8 == BPF_CMPXCHG;
            if (class == BPF_JMP || class == BPF_JMP32) && op != BPF_CALL && op != BPF_EXIT {
                // Invalid targets are ignored here, and rejected if they are reached.
                let target = scan_pc.checked_add_signed(isize::from(inst.offset()) + 1);
                if let Some(entry) = target.and_then(|pc| terminating_contexts.get_mut(pc)) {
                    *entry = Some(Default::default());
                }
                if op != BPF_JA {
                    if let Some(entry) = terminating_contexts.get_mut(scan_pc + 1) {
                        *entry = Some(Default::default());
                    }
                }
            } else if is_cmpxchg {
                if let Some(entry) = terminating_contexts.get_mut(scan_pc + 1) {
                    *entry = Some(Default::default());
                }
            }
            scan_pc += 1;
        }
    }

    let mut context = ComputationContext::default();
    for (i, t) in calling_context.args.iter().enumerate() {
        // The parameter registers are r1 to r5.
        context
            .set_reg((i + 1) as u8, t.clone())
            .map_err(|kind| VerifierError { kind, pc: None })?;
    }
    let states = vec![context];
    let mut verification_context =
        VerificationContext::new(calling_context, logger, &code, states, terminating_contexts);
    while let Some(mut context) = verification_context.states.pop() {
        if let Some(Some(terminating_contexts)) =
            verification_context.terminating_contexts.get(context.pc)
        {
            // Check whether there exist a context that terminate and prove that this context does
            // also terminate.
            if let Some(ending_context) = terminating_contexts.find_greater_or_equal(&context) {
                // One such context has been found, this proves the current context terminates.
                // If the context has a parent, register the data dependencies and try to terminate
                // it.
                if let Some(parent) = context.parent.take() {
                    parent.dependencies.update(|d| d.merge(ending_context.dependencies));
                    if let Some(parent) = Rc::into_inner(parent) {
                        parent.terminate(&mut verification_context)?;
                    }
                }
                continue;
            }
        }
        if verification_context.iteration > 10 * BPF_MAX_INSTS {
            return error_and_log(
                verification_context.logger,
                VerifierError { kind: VerifierErrorKind::ComplexityLimitExceeded, pc: None },
            );
        }
        if context.pc >= code.len() {
            return error_and_log(
                verification_context.logger,
                VerifierError { kind: VerifierErrorKind::FellOffProgramEnd, pc: Some(context.pc) },
            );
        }
        let first_successor = verification_context.states.len();
        if let Err(kind) = (&context).visit(&mut verification_context, code[context.pc]) {
            return error_and_log(
                verification_context.logger,
                VerifierError { kind, pc: Some(context.pc) },
            );
        }
        // All the contexts pushed while visiting `&context` are its successors, and are created
        // without a parent. Register `context` as their shared parent, or terminate it now if it
        // has no successors (i.e. `exit`).
        if let Some((last, rest)) = verification_context.states[first_successor..].split_last_mut()
        {
            let parent = Rc::new(context);
            for successor in rest {
                successor.parent = Some(Rc::clone(&parent));
            }
            last.parent = Some(parent);
        } else {
            debug_assert_eq!(code[context.pc].code(), BPF_JMP | BPF_EXIT);
            context.terminate(&mut verification_context)?;
        }
        verification_context.iteration += 1;
    }

    let struct_access_instructions = verification_context
        .memory_access_instructions
        .into_iter()
        .filter_map(|access| match access {
            MemoryAccess::Struct(s) => Some(s),
            MemoryAccess::Unaccessed | MemoryAccess::NonStruct => None,
        })
        .collect::<Vec<_>>();
    let CallingContext { maps, args, .. } = verification_context.calling_context;
    Ok(VerifiedEbpfProgram { code, struct_access_instructions, maps, args })
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum MemoryAccess {
    Unaccessed,
    NonStruct,
    Struct(StructAccess),
}

struct VerificationContext<'a> {
    /// The type information for the program arguments and the registered functions.
    calling_context: CallingContext,
    /// The logger to use.
    logger: &'a mut dyn VerifierLogger,
    /// The `ComputationContext` yet to be validated.
    states: Vec<ComputationContext>,
    /// The program being analyzed.
    code: &'a [EbpfInstruction],
    /// A counter used to generated unique ids for memory buffers and maps.
    counter: u64,
    /// The current iteration of the verifier. Used to ensure termination by limiting the number of
    /// iteration before bailing out.
    iteration: usize,
    /// Keep track of the context that terminates at a given pc. The list of context will all be
    /// incomparables as each time a bigger context is computed, the smaller ones are removed from
    /// the list. Indexed directly by `ProgramCounter` (`0..code.len()`) for O(1) lookup, and
    /// `None` if the pc is not a prune point.
    terminating_contexts: Vec<Option<TerminatingContexts>>,
    /// Per-PC record of whether a memory instruction accesses a `PtrToStruct` (`Struct`) or a
    /// non-struct pointer (`NonStruct`). Indexed directly by `ProgramCounter` (`0..code.len()`) to
    /// ensure a single instruction PC never mixes `PtrToStruct` rewriting with raw stack, buffer,
    /// or packet accesses, or accesses inconsistent struct fields.
    memory_access_instructions: Vec<MemoryAccess>,
}

impl<'a> VerificationContext<'a> {
    fn new(
        calling_context: CallingContext,
        logger: &'a mut dyn VerifierLogger,
        code: &'a [EbpfInstruction],
        states: Vec<ComputationContext>,
        terminating_contexts: Vec<Option<TerminatingContexts>>,
    ) -> Self {
        debug_assert_eq!(code.len(), terminating_contexts.len());
        let memory_access_instructions = vec![MemoryAccess::Unaccessed; code.len()];
        Self {
            calling_context,
            logger,
            states,
            code,
            counter: 0,
            iteration: 0,
            terminating_contexts,
            memory_access_instructions,
        }
    }

    fn next_id(&mut self) -> MemoryId {
        let id = self.counter;
        self.counter += 1;
        MemoryId { namespace: Namespace::Verification, id, parent: None }
    }

    /// Register an instruction that loads or stores memory, recording `Some(struct_access)` for
    /// struct field accesses and `None` for non-struct accesses.
    fn register_memory_access(
        &mut self,
        pc: ProgramCounter,
        struct_access: Option<StructAccess>,
    ) -> Result<(), VerifierErrorKind> {
        match (&mut self.memory_access_instructions[pc], struct_access) {
            (slot @ MemoryAccess::Unaccessed, Some(access)) => {
                *slot = MemoryAccess::Struct(access);
            }
            (slot @ MemoryAccess::Unaccessed, None) => {
                *slot = MemoryAccess::NonStruct;
            }
            (MemoryAccess::NonStruct, None) => {}
            (MemoryAccess::Struct(existing), Some(access)) => {
                if *existing != access {
                    return Err(VerifierErrorKind::InconsistentStructFieldAccess);
                }
            }
            (MemoryAccess::Struct(_), None) | (MemoryAccess::NonStruct, Some(_)) => {
                return Err(VerifierErrorKind::InconsistentMemoryAccess);
            }
        }
        Ok(())
    }
}

const STACK_ELEMENT_SIZE: usize = std::mem::size_of::<u64>();

/// An offset inside the stack. The offset is from the end of the stack.
/// downward.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct StackOffset(ScalarValueData);

impl Default for StackOffset {
    fn default() -> Self {
        Self(BPF_STACK_SIZE.into())
    }
}

impl StackOffset {
    /// Returns an error if the current offset is not valid for element access, distinguishing
    /// variable offsets from out of bounds ones.
    fn check_valid_offset(&self) -> Result<(), VerifierErrorKind> {
        if !self.0.is_known() {
            return Err(VerifierErrorKind::VariableStackOffset);
        }
        if self.0.value >= (BPF_STACK_SIZE as u64) {
            return Err(VerifierErrorKind::StackAccessOutOfBounds);
        }
        Ok(())
    }

    /// Whether the current offset is within the stack bounds, inclusive of `BPF_STACK_SIZE`.
    fn is_within_stack(&self) -> bool {
        self.0.is_known() && self.0.value <= (BPF_STACK_SIZE as u64)
    }

    /// The value of the register.
    fn reg(&self) -> ScalarValueData {
        self.0
    }

    /// The index into the stack array this offset points to. Can be called only if
    /// `is_within_stack()` is true.
    fn array_index(&self) -> usize {
        debug_assert!(self.is_within_stack());
        usize::try_from(self.0.value).unwrap() / STACK_ELEMENT_SIZE
    }

    /// The offset inside the aligned u64 in the stack.
    fn sub_index(&self) -> usize {
        debug_assert!(self.is_within_stack());
        usize::try_from(self.0.value).unwrap() % STACK_ELEMENT_SIZE
    }

    fn add<T: Into<ScalarValueData>>(self, rhs: T) -> Self {
        Self(self.0 + rhs)
    }
}

// The initialized elements of the stack are tracked in a `u64` bitmask.
const _: () = assert!(BPF_STACK_SIZE / STACK_ELEMENT_SIZE <= u64::BITS as usize);

/// Returns an iterator over the indices of the bits set in `mask`, in increasing order.
fn bit_indices(mut mask: u64) -> impl Iterator<Item = usize> {
    std::iter::from_fn(move || {
        if mask == 0 {
            return None;
        }
        let index = mask.trailing_zeros() as usize;
        mask &= mask - 1;
        Some(index)
    })
}

/// The state of the stack
///
/// Only the initialized elements are stored, densely and in increasing index order. The storage is
/// shared between the clones made for each verified instruction and copied on write. This makes
/// cloning cheap and comparing two stacks, the hot path of state pruning, a linear scan.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
struct Stack {
    /// Bit `i` is set iff element `i` is initialized.
    mask: u64,
    /// The initialized elements, in increasing index order.
    data: Arc<Vec<Type>>,
}

impl Stack {
    fn bit(index: usize) -> u64 {
        assert!(index < u64::BITS as usize);
        1 << index
    }

    /// Returns the position of the element at `index` in `data`, or the position where it must be
    /// inserted if it is not initialized.
    fn position(&self, index: usize) -> usize {
        (self.mask & (Self::bit(index) - 1)).count_ones() as usize
    }

    /// Replace all instances of the NullOr type with the given `null_id` to either 0 or the
    /// subtype depending on `is_null`
    fn set_null(&mut self, null_id: &MemoryId, is_null: bool) {
        if !self.data.iter().any(|t| matches!(t, Type::NullOr { id, .. } if id == null_id)) {
            return;
        }
        for t in Arc::make_mut(&mut self.data).iter_mut() {
            t.set_null(null_id, is_null);
        }
    }

    fn get(&self, index: usize) -> &Type {
        if self.mask & Self::bit(index) == 0 {
            &Type::UNINITIALIZED
        } else {
            &self.data[self.position(index)]
        }
    }

    fn set(&mut self, index: usize, t: Type) {
        let bit = Self::bit(index);
        let position = self.position(index);
        let is_set = self.mask & bit != 0;
        if t == Type::UNINITIALIZED {
            if is_set {
                Arc::make_mut(&mut self.data).remove(position);
                self.mask &= !bit;
            }
        } else if is_set {
            if self.data[position] != t {
                Arc::make_mut(&mut self.data)[position] = t;
            }
        } else {
            Arc::make_mut(&mut self.data).insert(position, t);
            self.mask |= bit;
        }
    }

    /// Uninitializes all the elements whose bit is not set in `mask`.
    fn retain(&mut self, mask: u64) {
        if self.mask & !mask == 0 {
            return;
        }
        if mask == 0 {
            match Arc::get_mut(&mut self.data) {
                Some(data) => data.clear(),
                None => self.data = Default::default(),
            }
            self.mask = 0;
            return;
        }

        let mut indices = bit_indices(self.mask);
        Arc::make_mut(&mut self.data).retain(|_| mask & Self::bit(indices.next().unwrap()) != 0);
        self.mask &= mask;
    }

    fn extract_sub_value(value: u64, offset: usize, byte_count: usize) -> u64 {
        NativeEndian::read_uint(&value.as_bytes()[offset..], byte_count)
    }

    fn insert_sub_value(mut original: u64, value: u64, width: DataWidth, offset: usize) -> u64 {
        let byte_count = width.bytes();
        let original_buf = original.as_mut_bytes();
        let value_buf = value.as_bytes();
        original_buf[offset..(byte_count + offset)].copy_from_slice(&value_buf[..byte_count]);
        original
    }

    fn write_data_ptr(
        &mut self,
        mut offset: StackOffset,
        bytes: u64,
    ) -> Result<(), VerifierErrorKind> {
        for i in 0..bytes {
            self.store(offset, Type::UNKNOWN_SCALAR, DataWidth::U8)?;
            offset = offset.add(1);
        }
        Ok(())
    }

    fn read_data_ptr(&self, offset: StackOffset, bytes: u64) -> Result<(), VerifierErrorKind> {
        let read_element = |index: usize,
                            start_offset: usize,
                            end_offset: usize|
         -> Result<(), VerifierErrorKind> {
            match self.get(index) {
                Type::ScalarValue(data) => {
                    debug_assert!(end_offset > start_offset);
                    let unwritten_bits = Self::extract_sub_value(
                        data.unwritten_mask,
                        start_offset,
                        end_offset - start_offset,
                    );
                    if unwritten_bits == 0 {
                        Ok(())
                    } else {
                        Err(VerifierErrorKind::UninitializedStackRead)
                    }
                }
                _ => Err(VerifierErrorKind::NonScalarStackRead),
            }
        };
        if bytes == 0 {
            return Ok(());
        }

        if bytes as usize > BPF_STACK_SIZE {
            return Err(VerifierErrorKind::StackAccessOutOfBounds);
        }

        offset.check_valid_offset()?;

        let end_offset = offset.add(bytes);
        if !end_offset.is_within_stack() {
            return Err(VerifierErrorKind::StackAccessOutOfBounds);
        }

        // Handle the case where all the data is contained in a single element excluding the last
        // byte (the case when the read ends at an element edge, i.e. `end_offset.sub_index()==0`,
        // is covered by the default path below).
        if offset.array_index() == end_offset.array_index() {
            return read_element(offset.array_index(), offset.sub_index(), end_offset.sub_index());
        }

        // Handle the first element, that might be partial.
        read_element(offset.array_index(), offset.sub_index(), STACK_ELEMENT_SIZE)?;

        // Handle the last element, that might be partial.
        if end_offset.sub_index() != 0 {
            read_element(end_offset.array_index(), 0, end_offset.sub_index())?;
        }

        // Handle the any full type between beginning and end.
        for i in (offset.array_index() + 1)..end_offset.array_index() {
            read_element(i, 0, STACK_ELEMENT_SIZE)?;
        }

        Ok(())
    }

    fn store(
        &mut self,
        offset: StackOffset,
        value: Type,
        width: DataWidth,
    ) -> Result<(), VerifierErrorKind> {
        offset.check_valid_offset()?;
        if offset.sub_index() % width.bytes() != 0 {
            return Err(VerifierErrorKind::MisalignedStackAccess);
        }

        let index = offset.array_index();
        if width == DataWidth::U64 {
            self.set(index, value);
        } else {
            match value {
                Type::ScalarValue(data) => {
                    if Self::extract_sub_value(data.unwritten_mask, 0, width.bytes()) != 0 {
                        return Err(VerifierErrorKind::InvalidStoredValue);
                    }
                    let old_data = match self.get(index) {
                        Type::ScalarValue(data) => *data,
                        _ => {
                            // The value in the stack is not a scalar. Let consider it an scalar
                            // value with no written bits.
                            ScalarValueData::UNINITIALIZED
                        }
                    };
                    let sub_index = offset.sub_index();
                    let value =
                        Self::insert_sub_value(old_data.value, data.value, width, sub_index);
                    let unknown_mask = Self::insert_sub_value(
                        old_data.unknown_mask,
                        data.unknown_mask,
                        width,
                        sub_index,
                    );
                    let unwritten_mask = Self::insert_sub_value(
                        old_data.unwritten_mask,
                        data.unwritten_mask,
                        width,
                        sub_index,
                    );
                    let urange = U64Range::compute_range_for_bytes_swap(
                        old_data.urange,
                        data.urange,
                        sub_index,
                        0,
                        width.bytes(),
                    );
                    self.set(
                        index,
                        Type::ScalarValue(ScalarValueData::new(
                            value,
                            unknown_mask,
                            unwritten_mask,
                            urange,
                        )),
                    );
                }
                _ => {
                    return Err(VerifierErrorKind::PartialNonScalarStackStore);
                }
            }
        }
        Ok(())
    }

    fn load(&self, offset: StackOffset, width: DataWidth) -> Result<Type, VerifierErrorKind> {
        offset.check_valid_offset()?;
        if offset.sub_index() % width.bytes() != 0 {
            return Err(VerifierErrorKind::MisalignedStackAccess);
        }

        let index = offset.array_index();
        let loaded_type = self.get(index).clone();
        let result = if width == DataWidth::U64 {
            loaded_type
        } else {
            match loaded_type {
                Type::ScalarValue(data) => {
                    let sub_index = offset.sub_index();
                    let value = Self::extract_sub_value(data.value, sub_index, width.bytes());
                    let unknown_mask =
                        Self::extract_sub_value(data.unknown_mask, sub_index, width.bytes());
                    let unwritten_mask =
                        Self::extract_sub_value(data.unwritten_mask, sub_index, width.bytes());
                    let urange = U64Range::compute_range_for_bytes_swap(
                        0.into(),
                        data.urange,
                        0,
                        sub_index,
                        width.bytes(),
                    );
                    Type::ScalarValue(ScalarValueData::new(
                        value,
                        unknown_mask,
                        unwritten_mask,
                        urange,
                    ))
                }
                _ => {
                    return Err(VerifierErrorKind::PartialNonScalarStackLoad);
                }
            }
        };
        if !result.is_initialized() {
            return Err(VerifierErrorKind::UninitializedStackRead);
        }
        Ok(result)
    }
}

/// Two types are ordered with `t1` > `t2` if a proof that a program in a state `t1` finish is also
/// a proof that a program in a state `t2` finish.
impl PartialOrd for Stack {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        if self.mask == other.mask && Arc::ptr_eq(&self.data, &other.data) {
            return Some(Ordering::Equal);
        }
        let mut result = match (self.mask & !other.mask != 0, !self.mask & other.mask != 0) {
            (true, true) => return None,
            (true, false) => Ordering::Less,
            (false, true) => Ordering::Greater,
            (false, false) => Ordering::Equal,
        };
        for index in bit_indices(self.mask & other.mask) {
            result = associate_orderings(result, self.get(index).partial_cmp(other.get(index))?)?;
        }
        Some(result)
    }
}

macro_rules! bpf_log {
    ($context:ident, $verification_context:ident, $($msg:tt)*) => {
        if $verification_context.logger.is_enabled() {
            let line = format!(
                "{}: ({:02x}) {}",
                $context.pc,
                $verification_context.code[$context.pc].code(),
                format_args!($($msg)*)
            );
            $verification_context.logger.log(line.as_bytes());
        }
    };
}

/// The state of the computation as known by the verifier at a given point in time.
#[derive(Debug, Default)]
struct ComputationContext {
    /// The program counter.
    pc: ProgramCounter,
    /// Register 0 to 9.
    registers: [Type; GENERAL_REGISTER_COUNT as usize],
    /// The state of the stack.
    stack: Stack,
    /// The dynamically known bounds of buffers indexed by their ids.
    array_bounds: BTreeMap<MemoryId, u64>,
    /// The currently allocated resources.
    resources: BTreeSet<MemoryId>,
    /// The previous context in the computation.
    parent: Option<Rc<ComputationContext>>,
    /// The data dependencies of this context. This is used to broaden a known ending context to
    /// help cutting computation branches. The verification is single-threaded, and the successors
    /// holding a reference to their parent add their dependencies to it.
    dependencies: Cell<DataDependencies>,
}

#[cfg(test)]
impl Clone for ComputationContext {
    fn clone(&self) -> Self {
        Self {
            pc: self.pc,
            registers: self.registers.clone(),
            stack: self.stack.clone(),
            array_bounds: self.array_bounds.clone(),
            resources: self.resources.clone(),
            parent: None,
            // dependencies are erased as they must always be used on the same instance of the
            // context.
            dependencies: Default::default(),
        }
    }
}

/// parent and dependencies are ignored for the comparison, as they do not matter for termination.
impl PartialEq for ComputationContext {
    fn eq(&self, other: &Self) -> bool {
        self.pc == other.pc
            && self.registers == other.registers
            && self.stack == other.stack
            && self.array_bounds == other.array_bounds
            && self.resources == other.resources
    }
}

impl ComputationContext {
    /// Replace all instances of the NullOr type with the given `null_id` to either 0 or the
    /// subtype depending on `is_null`
    fn set_null(&mut self, null_id: &MemoryId, is_null: bool) {
        for i in 0..self.registers.len() {
            self.registers[i].set_null(null_id, is_null);
        }
        self.stack.set_null(null_id, is_null);
    }

    fn reg(&self, index: Register) -> Result<Type, VerifierErrorKind> {
        if index >= REGISTER_COUNT {
            return Err(VerifierErrorKind::InvalidRegister(index));
        }
        if index < GENERAL_REGISTER_COUNT {
            Ok(self.registers[index as usize].clone())
        } else {
            Ok(Type::PtrToStack { offset: StackOffset::default() })
        }
    }

    fn set_reg(&mut self, index: Register, reg_type: Type) -> Result<(), VerifierErrorKind> {
        if index >= REGISTER_COUNT {
            return Err(VerifierErrorKind::InvalidRegister(index));
        }
        if index >= GENERAL_REGISTER_COUNT {
            return Err(VerifierErrorKind::WriteToReadOnlyRegister(index));
        }
        self.registers[index as usize] = reg_type;
        Ok(())
    }

    fn update_array_bounds(&mut self, id: MemoryId, new_bound: ScalarValueData) {
        let new_bound_min = new_bound.min();
        self.array_bounds
            .entry(id)
            .and_modify(|v| *v = std::cmp::max(*v, new_bound_min))
            .or_insert(new_bound_min);
    }

    fn get_map_schema(&self, argument: u8) -> Result<MapSchema, VerifierErrorKind> {
        match self.reg(argument + 1)? {
            Type::ConstPtrToMap { schema, .. } => Ok(schema),
            _ => Err(VerifierErrorKind::HelperArgumentNotMap(argument)),
        }
    }

    fn next(&self) -> Result<Self, VerifierErrorKind> {
        self.jump_with_offset(0)
    }

    /// Returns a new `ComputationContext` where the pc has jump by `offset + 1`. In particular,
    /// the next instruction is reached with `jump_with_offset(0)`.
    ///
    /// This does not check that the target is inside the program: falling off the end of the
    /// program is reported by the main verification loop. Use `checked_jump_with_offset` for
    /// explicit jumps.
    ///
    /// The returned context has no parent. The parent is set by `verify_program` once the
    /// current instruction has been fully visited, by moving `self` into an `Rc` shared by all
    /// its successors, instead of cloning it.
    fn jump_with_offset(&self, offset: i16) -> Result<Self, VerifierErrorKind> {
        let pc = self
            .pc
            .checked_add_signed(offset.into())
            .and_then(|v| v.checked_add_signed(1))
            .ok_or(VerifierErrorKind::JumpOutOfBounds)?;
        let result = Self {
            pc,
            registers: self.registers.clone(),
            stack: self.stack.clone(),
            array_bounds: self.array_bounds.clone(),
            resources: self.resources.clone(),
            parent: None,
            dependencies: Default::default(),
        };
        Ok(result)
    }

    /// Same as `jump_with_offset`, but also fails if the target of the jump is outside of the
    /// program.
    fn checked_jump_with_offset(
        &self,
        verification_context: &VerificationContext<'_>,
        offset: i16,
    ) -> Result<Self, VerifierErrorKind> {
        let result = self.jump_with_offset(offset)?;
        if result.pc >= verification_context.code.len() {
            return Err(VerifierErrorKind::JumpOutOfBounds);
        }
        Ok(result)
    }

    fn check_memory_access(
        &self,
        dst_offset: ScalarValueData,
        dst_buffer_size: u64,
        instruction_offset: i16,
        width: usize,
    ) -> Result<(), VerifierErrorKind> {
        let memory_range = dst_offset.urange + instruction_offset + U64Range::new(0, width as u64);
        if memory_range.max > dst_buffer_size {
            return Err(VerifierErrorKind::OutOfBoundsMemoryAccess);
        }
        Ok(())
    }

    /// Checks that the atomic access to `addr + field.offset` is allowed: it
    /// must target either the stack or a map value, and it must be naturally
    /// aligned for `field.width`.
    ///
    /// The stack and map values are at least 8-byte aligned, so it is
    /// sufficient to check the offset of the access relative to the start of
    /// the buffer. The offset is tracked as a `ScalarValueData`, so the check
    /// requires the low bits of the offset to be known and zero.
    fn check_atomic_access(&self, addr: &Type, field: Field) -> Result<(), VerifierErrorKind> {
        let addr = addr.inner(self)?;
        let base_offset = match *addr {
            Type::PtrToStack { offset } => offset.reg(),
            Type::PtrToMemory { offset, origin, .. } if origin.is_map_value() => offset,
            _ => return Err(VerifierErrorKind::AtomicAccessNotAllowed),
        };
        let alignment_mask = (field.width.bytes() as u64) - 1;
        // Adding a constant preserves the low bits of the result only if the
        // low bits of the other operand are known.
        if base_offset.unknown_mask & alignment_mask != 0
            || base_offset.value.wrapping_add_signed(field.offset.into()) & alignment_mask != 0
        {
            return Err(VerifierErrorKind::MisalignedAtomicAccess);
        }
        Ok(())
    }

    fn store_memory(
        &mut self,
        context: &mut VerificationContext<'_>,
        pc: ProgramCounter,
        addr: &Type,
        field: Field,
        value: Type,
    ) -> Result<(), VerifierErrorKind> {
        let addr = addr.inner(self)?;
        let is_initialized_scalar =
            matches!(value, Type::ScalarValue(data) if data.is_fully_initialized());
        let struct_access = match *addr {
            Type::PtrToStack { offset } => {
                let offset_sum = offset.add(field.offset);
                self.stack.store(offset_sum, value, field.width)?;
                None
            }
            Type::PtrToMemory { offset, buffer_size, origin, .. } if origin.is_writable() => {
                self.check_memory_access(offset, buffer_size, field.offset, field.width.bytes())?;
                None
            }
            Type::PtrToMemory { .. } => {
                return Err(VerifierErrorKind::WriteToReadOnlyMemory);
            }
            Type::PtrToStruct { ref id, offset, ref descriptor, .. } => {
                let field_desc = descriptor
                    .find_field(offset, field)
                    .ok_or(VerifierErrorKind::InvalidStructFieldAccess)?;

                if !matches!(field_desc.field_type, FieldType::MutableScalar { .. }) {
                    return Err(VerifierErrorKind::WriteToReadOnlyField);
                }

                Some(StructAccess {
                    pc,
                    memory_id: id.clone(),
                    field_offset: field_desc.offset,
                    is_32_bit_ptr_load: false,
                })
            }
            Type::PtrToArray { ref id, offset } => {
                self.check_memory_access(
                    offset,
                    *self.array_bounds.get(&id).unwrap_or(&0),
                    field.offset,
                    field.width.bytes(),
                )?;
                None
            }
            _ => return Err(VerifierErrorKind::StoreToNonPointer),
        };

        // Private data should not be leaked outside the stack.
        if !matches!(*addr, Type::PtrToStack { .. }) && !is_initialized_scalar {
            return Err(VerifierErrorKind::InvalidStoredValue);
        }
        context.register_memory_access(pc, struct_access)?;
        Ok(())
    }

    fn load_memory(
        &self,
        context: &mut VerificationContext<'_>,
        addr: &Type,
        field: Field,
    ) -> Result<Type, VerifierErrorKind> {
        let addr = addr.inner(self)?;
        let (loaded_type, struct_access) = match *addr {
            Type::PtrToStack { offset } => {
                let offset_sum = offset.add(field.offset);
                (self.stack.load(offset_sum, field.width)?, None)
            }
            Type::PtrToMemory { offset, buffer_size, .. } => {
                self.check_memory_access(offset, buffer_size, field.offset, field.width.bytes())?;
                (Type::UNKNOWN_SCALAR, None)
            }
            Type::PtrToStruct { ref id, offset, ref descriptor, .. } => {
                let field_desc = descriptor
                    .find_field(offset, field)
                    .ok_or(VerifierErrorKind::InvalidStructFieldAccess)?;

                let (return_type, is_32_bit_ptr_load) = match &field_desc.field_type {
                    FieldType::Scalar { .. } | FieldType::MutableScalar { .. } => {
                        (Type::UNKNOWN_SCALAR, false)
                    }
                    FieldType::PtrToArray { id: array_id, is_32_bit } => (
                        Type::PtrToArray { id: array_id.prepended(id.clone()), offset: 0.into() },
                        *is_32_bit,
                    ),
                    FieldType::PtrToEndArray { id: array_id, is_32_bit } => {
                        (Type::PtrToEndArray { id: array_id.prepended(id.clone()) }, *is_32_bit)
                    }
                    FieldType::PtrToMemory { id: memory_id, buffer_size, is_32_bit } => (
                        Type::PtrToMemory {
                            id: memory_id.prepended(id.clone()),
                            offset: 0.into(),
                            buffer_size: *buffer_size as u64,
                            origin: PointerOrigin::KernelReadOnly,
                        },
                        *is_32_bit,
                    ),
                    FieldType::NullablePtrToMemory { id: memory_id, buffer_size, is_32_bit } => {
                        let id = memory_id.prepended(id.clone());
                        (
                            Type::NullOr {
                                id: id.clone(),
                                inner: Arc::new(Type::PtrToMemory {
                                    id,
                                    offset: 0.into(),
                                    buffer_size: *buffer_size as u64,
                                    origin: PointerOrigin::KernelReadOnly,
                                }),
                            },
                            *is_32_bit,
                        )
                    }
                };

                (
                    return_type,
                    Some(StructAccess {
                        pc: self.pc,
                        memory_id: id.clone(),
                        field_offset: field_desc.offset,
                        is_32_bit_ptr_load,
                    }),
                )
            }
            Type::PtrToArray { ref id, offset } => {
                self.check_memory_access(
                    offset,
                    *self.array_bounds.get(&id).unwrap_or(&0),
                    field.offset,
                    field.width.bytes(),
                )?;
                (Type::UNKNOWN_SCALAR, None)
            }
            _ => return Err(VerifierErrorKind::LoadFromNonPointer),
        };
        context.register_memory_access(self.pc, struct_access)?;
        Ok(loaded_type)
    }

    /**
     * Given the given `return_value` in a method signature, return the concrete type to use,
     * updating the `next` context is needed.
     */
    fn resolve_return_value(
        &self,
        verification_context: &mut VerificationContext<'_>,
        return_value: &Type,
        next: &mut ComputationContext,
    ) -> Result<Type, VerifierErrorKind> {
        match return_value {
            Type::AliasParameter { parameter_index } => self.reg(parameter_index + 1),
            Type::ReleasableParameter { id, inner } => {
                let id = verification_context.next_id().prepended(id.clone());
                next.resources.insert(id.clone());
                Ok(Type::Releasable {
                    id,
                    inner: Arc::new(self.resolve_return_value(
                        verification_context,
                        inner,
                        next,
                    )?),
                })
            }
            Type::NullOrParameter(t) => {
                let id = verification_context.next_id();
                Ok(Type::NullOr {
                    id,
                    inner: Arc::new(self.resolve_return_value(verification_context, t, next)?),
                })
            }
            Type::MapValueParameter { map_ptr_index } => {
                let schema = self.get_map_schema(*map_ptr_index)?;
                let id = verification_context.next_id();
                let origin = if schema.flags.contains(MapFlags::ProgReadOnly) {
                    PointerOrigin::MapReadOnly
                } else {
                    PointerOrigin::MapWritable
                };
                Ok(Type::PtrToMemory {
                    id,
                    offset: 0.into(),
                    buffer_size: schema.value_size as u64,
                    origin,
                })
            }
            Type::MemoryParameter { size, .. } => {
                let buffer_size = size.size(self)?;
                let id = verification_context.next_id();
                Ok(Type::PtrToMemory {
                    id,
                    offset: 0.into(),
                    buffer_size,
                    origin: PointerOrigin::MapWritable,
                })
            }
            Type::PtrToMemory { id, offset, buffer_size, origin } => {
                let id = id.prepended(verification_context.next_id());
                Ok(Type::PtrToMemory {
                    id,
                    offset: *offset,
                    buffer_size: *buffer_size,
                    origin: *origin,
                })
            }
            Type::PtrToStruct { id, offset, descriptor } => {
                let id = id.prepended(verification_context.next_id());
                Ok(Type::PtrToStruct { id, offset: *offset, descriptor: descriptor.clone() })
            }
            t => Ok(t.clone()),
        }
    }

    fn compute_source(&self, src: Source) -> Result<Type, VerifierErrorKind> {
        match src {
            Source::Reg(reg) => self.reg(reg),
            Source::Value(v) => Ok(v.into()),
        }
    }

    fn apply_computation(
        context: &ComputationContext,
        op1: Type,
        op2: Type,
        alu_type: AluType,
        op: impl Fn(ScalarValueData, ScalarValueData) -> ScalarValueData,
    ) -> Result<Type, VerifierErrorKind> {
        let result: Type = match (alu_type, op1.inner(context)?, op2.inner(context)?) {
            (_, Type::ScalarValue(data1), Type::ScalarValue(data2)) => op(*data1, *data2).into(),
            (
                AluType::Add,
                Type::ScalarValue(_),
                Type::PtrToStack { .. }
                | Type::PtrToMemory { .. }
                | Type::PtrToStruct { .. }
                | Type::PtrToArray { .. },
            ) => {
                return Self::apply_computation(context, op2, op1, alu_type, op);
            }
            // Pointer arithmetic with a scalar that is not fully initialized (either never
            // written, or derived from a pointer value) is prohibited: it would allow the
            // pointer value to leak through the resulting offset.
            (
                alu_type,
                Type::PtrToStack { .. }
                | Type::PtrToMemory { .. }
                | Type::PtrToStruct { .. }
                | Type::PtrToArray { .. },
                Type::ScalarValue(data),
            ) if alu_type.is_ptr_compatible() && !data.is_fully_initialized() => {
                return Err(VerifierErrorKind::UninitializedPointerArithmetic);
            }
            (alu_type, Type::PtrToStack { offset: x }, Type::ScalarValue(data))
                if alu_type.is_ptr_compatible() =>
            {
                const BPF_MAX_VAR_OFF: u64 = 1 << 29;
                let offset = op(x.reg(), *data);
                if offset.max() > BPF_MAX_VAR_OFF {
                    return Err(VerifierErrorKind::PointerOffsetOverflow);
                }
                Type::PtrToStack { offset: StackOffset(offset) }
            }
            (
                alu_type,
                Type::PtrToMemory { offset: x, .. } | Type::PtrToStruct { offset: x, .. },
                Type::ScalarValue(data),
            ) if alu_type.is_ptr_compatible() => {
                const BPF_MAX_VAR_OFF: u64 = 1 << 29;
                let offset = op(*x, *data);
                if offset.max() > BPF_MAX_VAR_OFF {
                    return Err(VerifierErrorKind::PointerOffsetOverflow);
                }
                op1.with_offset(offset)
            }
            (AluType::Add, Type::PtrToArray { offset: x, .. }, Type::ScalarValue(data)) => {
                let offset =
                    x.checked_add(*data).ok_or(VerifierErrorKind::PointerOffsetOverflow)?;
                if offset.max() > MAX_PACKET_OFFSET {
                    return Err(VerifierErrorKind::PointerOffsetOverflow);
                }
                op1.with_offset(offset)
            }
            (AluType::Sub, Type::PtrToArray { offset: x, .. }, Type::ScalarValue(data)) => {
                let offset =
                    x.checked_sub(*data).ok_or(VerifierErrorKind::PointerOffsetOverflow)?;
                if offset.max() > MAX_PACKET_OFFSET {
                    return Err(VerifierErrorKind::PointerOffsetOverflow);
                }
                op1.with_offset(offset)
            }
            (
                AluType::Sub,
                Type::PtrToMemory { id: id1, offset: x1, .. },
                Type::PtrToMemory { id: id2, offset: x2, .. },
            )
            | (
                AluType::Sub,
                Type::PtrToStruct { id: id1, offset: x1, .. },
                Type::PtrToStruct { id: id2, offset: x2, .. },
            )
            | (
                AluType::Sub,
                Type::PtrToArray { id: id1, offset: x1 },
                Type::PtrToArray { id: id2, offset: x2 },
            ) if id1 == id2 => Type::from(op(*x1, *x2)),
            (AluType::Sub, Type::PtrToStack { offset: x1 }, Type::PtrToStack { offset: x2 }) => {
                Type::from(op(x1.reg(), x2.reg()))
            }
            (
                AluType::Sub,
                Type::PtrToArray { id: id1, .. },
                Type::PtrToEndArray { id: id2, .. },
            )
            | (
                AluType::Sub,
                Type::PtrToEndArray { id: id1, .. },
                Type::PtrToArray { id: id2, .. },
            ) if id1 == id2 => Type::UNKNOWN_SCALAR,
            _ => Type::default(),
        };
        Ok(result)
    }

    fn alu(
        &self,
        op_name: Option<&str>,
        verification_context: &mut VerificationContext<'_>,
        dst: Register,
        src: Source,
        alu_type: AluType,
        op: impl Fn(ScalarValueData, ScalarValueData) -> ScalarValueData,
    ) -> Result<(), VerifierErrorKind> {
        if let Some(op_name) = op_name {
            bpf_log!(
                self,
                verification_context,
                "{op_name} {}, {}",
                display_register(dst),
                display_source(src)
            );
        }
        let op1 = self.reg(dst)?;
        let op2 = self.compute_source(src)?;
        let result = Self::apply_computation(self, op1, op2, alu_type, op)?;
        let mut next = self.next()?;
        next.set_reg(dst, result)?;
        verification_context.states.push(next);
        Ok(())
    }

    fn log_atomic_operation(
        &self,
        op_name: &str,
        verification_context: &mut VerificationContext<'_>,
        fetch: bool,
        dst: Register,
        offset: i16,
        src: Register,
    ) {
        bpf_log!(
            self,
            verification_context,
            "lock {}{} [{}{}], {}",
            if fetch { "fetch " } else { "" },
            op_name,
            display_register(dst),
            print_offset(offset),
            display_register(src),
        );
    }

    fn raw_atomic_operation(
        &self,
        op_name: &str,
        verification_context: &mut VerificationContext<'_>,
        width: DataWidth,
        fetch: bool,
        dst: Register,
        offset: i16,
        src: Register,
        op: impl FnOnce(&ComputationContext, Type, Type) -> Result<Type, VerifierErrorKind>,
    ) -> Result<(), VerifierErrorKind> {
        self.log_atomic_operation(op_name, verification_context, fetch, dst, offset, src);
        let addr = self.reg(dst)?;
        let value = self.reg(src)?;
        let field = Field::new(offset, width);
        self.check_atomic_access(&addr, field)?;
        let loaded_type = self.load_memory(verification_context, &addr, field)?;
        let result = op(self, loaded_type.clone(), value)?;
        let mut next = self.next()?;
        next.store_memory(verification_context, self.pc, &addr, field, result)?;
        if fetch {
            next.set_reg(src, loaded_type)?;
        }
        verification_context.states.push(next);
        Ok(())
    }

    fn atomic_operation(
        &self,
        op_name: &str,
        verification_context: &mut VerificationContext<'_>,
        width: DataWidth,
        fetch: bool,
        dst: Register,
        offset: i16,
        src: Register,
        alu_type: AluType,
        op: impl Fn(ScalarValueData, ScalarValueData) -> ScalarValueData,
    ) -> Result<(), VerifierErrorKind> {
        self.raw_atomic_operation(
            op_name,
            verification_context,
            width,
            fetch,
            dst,
            offset,
            src,
            |context: &ComputationContext, v1: Type, v2: Type| {
                Self::apply_computation(context, v1, v2, alu_type, op)
            },
        )
    }

    fn raw_atomic_cmpxchg(
        &self,
        op_name: &str,
        verification_context: &mut VerificationContext<'_>,
        dst: Register,
        offset: i16,
        src: Register,
        jump_width: JumpWidth,
        op: impl Fn(ScalarValueData, ScalarValueData) -> Result<Option<bool>, ()>,
    ) -> Result<(), VerifierErrorKind> {
        self.log_atomic_operation(op_name, verification_context, true, dst, offset, src);
        let width = match jump_width {
            JumpWidth::W32 => DataWidth::U32,
            JumpWidth::W64 => DataWidth::U64,
        };
        let addr = self.reg(dst)?;
        let field = Field::new(offset, width);
        self.check_atomic_access(&addr, field)?;
        let dst = self.load_memory(verification_context, &addr, field)?;
        let value = self.reg(src)?;
        let r0 = self.reg(0)?;
        let branch = self.compute_branch(JumpType::Eq, jump_width, &dst, &r0, op)?;
        // r0 = dst
        if branch.unwrap_or(true) {
            let mut next = self.next()?;
            let (dst, r0) =
                Type::constraint(&mut next, JumpType::Eq, jump_width, dst.clone(), r0.clone())?;
            next.set_reg(0, dst)?;
            next.store_memory(verification_context, self.pc, &addr, field, value)?;
            verification_context.states.push(next);
        }
        // r0 != dst
        if !branch.unwrap_or(false) {
            let mut next = self.next()?;
            let (dst, r0) = Type::constraint(&mut next, JumpType::Ne, jump_width, dst, r0)?;
            next.set_reg(0, dst.clone())?;
            next.store_memory(verification_context, self.pc, &addr, field, dst)?;
            verification_context.states.push(next);
        }

        Ok(())
    }
    fn endianness<BO: ByteOrder>(
        &self,
        op_name: &str,
        verification_context: &mut VerificationContext<'_>,
        dst: Register,
        width: DataWidth,
    ) -> Result<(), VerifierErrorKind> {
        bpf_log!(self, verification_context, "{op_name}{} {}", width.bits(), display_register(dst),);
        let bit_op = |value: u64| match width {
            DataWidth::U16 => BO::read_u16((value as u16).as_bytes()) as u64,
            DataWidth::U32 => BO::read_u32((value as u32).as_bytes()) as u64,
            DataWidth::U64 => BO::read_u64(value.as_bytes()),
            _ => {
                panic!("Unexpected bit width for endianness operation");
            }
        };
        let value = self.reg(dst)?;
        // Reject partially or uninitialized scalars (since 16- and 32-bit byte swaps
        // zero-extend the upper bits into `unwritten_mask == 0`). Pointers are rejected unless
        // `allow_ptr_leaks` is set, in which case they coerce to an unknown scalar.
        let new_value = match value.inner(self)? {
            Type::ScalarValue(data) if data.is_fully_initialized() => {
                Type::ScalarValue(ScalarValueData::new(
                    bit_op(data.value),
                    bit_op(data.unknown_mask),
                    0,
                    U64Range::max(),
                ))
            }
            Type::ScalarValue(_) => return Err(VerifierErrorKind::InvalidByteSwapTarget),
            _ if verification_context.calling_context.allow_ptr_leaks => Type::UNKNOWN_SCALAR,
            _ => return Err(VerifierErrorKind::InvalidByteSwapTarget),
        };
        let mut next = self.next()?;
        next.set_reg(dst, new_value)?;
        verification_context.states.push(next);
        Ok(())
    }

    fn compute_branch(
        &self,
        jump_type: JumpType,
        jump_width: JumpWidth,
        op1: &Type,
        op2: &Type,
        op: impl Fn(ScalarValueData, ScalarValueData) -> Result<Option<bool>, ()>,
    ) -> Result<Option<bool>, VerifierErrorKind> {
        let eval_same_region_ptr = |sx: ScalarValueData,
                                    sy: ScalarValueData,
                                    in_bounds: bool|
         -> Result<Option<bool>, ()> {
            if !sx.is_fully_initialized() || !sy.is_fully_initialized() {
                return Err(());
            }
            match jump_type {
                JumpType::Eq | JumpType::Ne => op(sx, sy),
                JumpType::Gt | JumpType::Ge | JumpType::Lt | JumpType::Le => {
                    if in_bounds {
                        op(sx, sy)
                    } else {
                        Ok(None)
                    }
                }
                JumpType::LooseComparaison | JumpType::StrictComparaison | JumpType::Unknown => {
                    Ok(None)
                }
            }
        };
        // Unwrap Releasable operands (verifying they have not been released) so
        // pointer comparisons work on their underlying pointer types.
        match (jump_width, op1.inner(self)?, op2.inner(self)?) {
            (_, Type::ScalarValue(data1), Type::ScalarValue(data2)) => op(*data1, *data2),
            (JumpWidth::W64, Type::ScalarValue(data), Type::NullOr { .. })
            | (JumpWidth::W64, Type::NullOr { .. }, Type::ScalarValue(data))
                if data.is_zero() =>
            {
                Ok(None)
            }

            (JumpWidth::W64, Type::ScalarValue(data), t) if data.is_zero() && t.is_non_zero() => {
                let non_zero =
                    ScalarValueData::UNKNOWN_WRITTEN.update_range(U64Range::new(1, u64::MAX));
                op(0.into(), non_zero)
            }

            (JumpWidth::W64, t, Type::ScalarValue(data)) if data.is_zero() && t.is_non_zero() => {
                let non_zero =
                    ScalarValueData::UNKNOWN_WRITTEN.update_range(U64Range::new(1, u64::MAX));
                op(non_zero, 0.into())
            }

            (JumpWidth::W64, Type::PtrToStack { offset: x }, Type::PtrToStack { offset: y }) => {
                let in_bounds = x.reg().max() <= (BPF_STACK_SIZE as u64)
                    && y.reg().max() <= (BPF_STACK_SIZE as u64);
                eval_same_region_ptr(x.reg(), y.reg(), in_bounds)
            }

            (
                JumpWidth::W64,
                Type::PtrToMemory { id: id1, offset: x, buffer_size: b1, .. },
                Type::PtrToMemory { id: id2, offset: y, buffer_size: b2, .. },
            ) if *id1 == *id2 => {
                let in_bounds = x.max() <= *b1 && y.max() <= *b2;
                eval_same_region_ptr(*x, *y, in_bounds)
            }

            (
                JumpWidth::W64,
                Type::PtrToStruct { id: id1, offset: x, .. },
                Type::PtrToStruct { id: id2, offset: y, .. },
            ) if *id1 == *id2 => eval_same_region_ptr(*x, *y, x.is_zero() && y.is_zero()),

            (
                JumpWidth::W64,
                Type::PtrToArray { id: id1, offset: x, .. },
                Type::PtrToArray { id: id2, offset: y, .. },
            ) if *id1 == *id2 => {
                let bound = *self.array_bounds.get(id1).unwrap_or(&0);
                eval_same_region_ptr(*x, *y, x.max() <= bound && y.max() <= bound)
            }

            (JumpWidth::W64, Type::PtrToArray { id: id1, .. }, Type::PtrToEndArray { id: id2 })
            | (JumpWidth::W64, Type::PtrToEndArray { id: id1 }, Type::PtrToArray { id: id2, .. })
                if *id1 == *id2 =>
            {
                Ok(None)
            }

            _ => Err(()),
        }
        .map_err(|_| VerifierErrorKind::InvalidComparison)
    }

    fn conditional_jump(
        &self,
        op_name: &str,
        verification_context: &mut VerificationContext<'_>,
        dst: Register,
        src: Source,
        offset: i16,
        jump_type: JumpType,
        jump_width: JumpWidth,
        op: impl Fn(ScalarValueData, ScalarValueData) -> Result<Option<bool>, ()>,
    ) -> Result<(), VerifierErrorKind> {
        bpf_log!(
            self,
            verification_context,
            "{op_name} {}, {}, {}",
            display_register(dst),
            display_source(src),
            print_jump_offset(offset),
        );
        let op1 = self.reg(dst)?;
        let op2 = self.compute_source(src.clone())?;
        let apply_constraints_and_register = |mut next: Self,
                                              jump_type: JumpType|
         -> Result<Self, VerifierErrorKind> {
            if jump_type != JumpType::Unknown {
                let (new_op1, new_op2) =
                    Type::constraint(&mut next, jump_type, jump_width, op1.clone(), op2.clone())?;
                if dst < GENERAL_REGISTER_COUNT {
                    next.set_reg(dst, new_op1)?;
                }
                match src {
                    Source::Reg(r) if r < GENERAL_REGISTER_COUNT => {
                        next.set_reg(r, new_op2)?;
                    }
                    _ => {
                        // Nothing to do
                    }
                }
            }
            Ok(next)
        };
        let branch = self.compute_branch(jump_type, jump_width, &op1, &op2, op)?;
        if branch.unwrap_or(true) {
            // Do the jump
            verification_context.states.push(apply_constraints_and_register(
                self.checked_jump_with_offset(verification_context, offset)?,
                jump_type,
            )?);
        }
        if !branch.unwrap_or(false) {
            // Skip the jump
            verification_context.states.push(apply_constraints_and_register(
                self.jump_with_offset(0)?,
                jump_type.invert(),
            )?);
        }
        Ok(())
    }

    /// Handles the termination of a `ComputationContext`, performing branch cutting optimization.
    ///
    /// This method is called when it has been proven that the current context terminates (e.g.,
    /// reaches an `exit` instruction).
    ///
    /// The following steps are performed:
    /// 1. **Dependency Calculation:** The data dependencies of the context are computed based on
    ///    the dependencies of its terminated children and the instruction at the current PC.
    /// 2. **Context Broadening:** At a prune point, the context's state is broadened by clearing
    ///    registers and stack slots that are *not* in the calculated data dependencies. This
    ///    optimization assumes that data not used by the terminated branch is irrelevant for
    ///    future execution paths.
    /// 3. **Termination Registration:** At a prune point, the broadened context is added to the
    ///    set of terminating contexts if it is not less than any existing terminating context at
    ///    the same PC.
    /// 4. **Parent Termination:** If all the children of the current context have terminated,
    ///    its parent context is recursively terminated.
    fn terminate(
        self,
        verification_context: &mut VerificationContext<'_>,
    ) -> Result<(), VerifierError> {
        let mut next = Some(self);
        // Because of the potential length of the parent chain, do not use recursion.
        while let Some(mut current) = next.take() {
            // Take the parent to process it at the end and not keep it in the terminating
            // contexts.
            let parent = current.parent.take();

            // 1. Compute the dependencies of the context using the dependencies of its children
            //    and the actual operation.
            let mut dependencies = current.dependencies.get();

            dependencies
                .visit(
                    &mut DataDependenciesVisitorContext {
                        calling_context: &verification_context.calling_context,
                        computation_context: &current,
                    },
                    verification_context.code[current.pc],
                )
                .map_err(|kind| VerifierError { kind, pc: Some(current.pc) })?;

            if let Some(terminating_contexts) =
                &mut verification_context.terminating_contexts[current.pc]
            {
                // 2. Clear the state depending on the dependencies states
                for register in 0..GENERAL_REGISTER_COUNT {
                    if !dependencies.has_reg(register) {
                        current
                            .set_reg(register, Default::default())
                            .map_err(|kind| VerifierError { kind, pc: Some(current.pc) })?;
                    }
                }
                current.stack.retain(dependencies.stack);

                // 3. Add the cleared state to the set of `terminating_contexts`
                terminating_contexts.insert(current, dependencies);
            }

            // 4. Register the computed dependencies in our parent, and terminate it if all
            //    dependencies has been computed.
            if let Some(parent) = parent {
                parent.dependencies.update(|d| d.merge(dependencies));
                // To check whether all dependencies have been computed, rely on the fact that the
                // Rc count of the parent keep track of how many dependencies are left.
                next = Rc::into_inner(parent);
            }
        }
        Ok(())
    }
}

impl Drop for ComputationContext {
    fn drop(&mut self) {
        let mut next = self.parent.take().and_then(Rc::into_inner);
        // Because of the potential length of the parent chain, do not use recursion.
        while let Some(mut current) = next {
            next = current.parent.take().and_then(Rc::into_inner);
        }
    }
}

/// Two types are ordered with `t1` > `t2` if a proof that a program in a state `t1` finish is also
/// a proof that a program in a state `t2` finish.
impl PartialOrd for ComputationContext {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        if self.pc != other.pc || self.resources.len() != other.resources.len() {
            return None;
        }
        let mut result = Type::compare_list(self.registers.iter(), other.registers.iter())?;
        result = associate_orderings(result, self.stack.partial_cmp(&other.stack)?)?;
        if self.resources != other.resources {
            return None;
        }
        let mut array_bound_iter1 = self.array_bounds.iter().peekable();
        let mut array_bound_iter2 = other.array_bounds.iter().peekable();
        let result = loop {
            match (array_bound_iter1.peek().cloned(), array_bound_iter2.peek().cloned()) {
                (None, None) => break result,
                (None, _) => break associate_orderings(result, Ordering::Greater)?,
                (_, None) => break associate_orderings(result, Ordering::Less)?,
                (Some((k1, v1)), Some((k2, v2))) => match k1.cmp(k2) {
                    Ordering::Equal => {
                        array_bound_iter1.next();
                        array_bound_iter2.next();
                        // The comparison is intentionally reversed (v2.cmp(v1) instead of
                        // v1.cmp(v2)). `v1` is the bound of the explored state (`self`) and `v2` is
                        // the bound of the current state (`other`). A smaller bound value
                        // represents a stronger safety guarantee (fewer assumed valid bytes,
                        // meaning a more restricted program). Therefore, a state with a smaller
                        // bound dominates (is "Greater" than) a state with a larger bound.
                        result = associate_orderings(result, v2.cmp(v1))?;
                    }
                    v @ Ordering::Less => {
                        array_bound_iter1.next();
                        result = associate_orderings(result, v)?;
                    }
                    v @ Ordering::Greater => {
                        array_bound_iter2.next();
                        result = associate_orderings(result, v)?;
                    }
                },
            }
        };
        Some(result)
    }
}

/// Represents the read data dependencies of an eBPF program branch.
///
/// This struct tracks which registers and stack positions are *read* by the
/// instructions within a branch of the eBPF program.  This information is used
/// during branch cutting optimization to broaden terminating contexts.
///
/// The verifier assumes that data not read by a terminated branch is irrelevant
/// for future execution paths and can be safely cleared.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
struct DataDependencies {
    /// A bitset of registers read by the children of a context.
    registers: u16,
    /// A bitset of stack positions read by the children of a context.
    stack: u64,
}

impl DataDependencies {
    #[inline]
    fn has_reg(&self, reg: Register) -> bool {
        (self.registers & (1_u16 << reg)) != 0
    }

    #[inline]
    fn add_reg(&mut self, reg: Register) {
        self.registers |= 1_u16 << reg;
    }

    #[inline]
    fn remove_reg(&mut self, reg: Register) -> bool {
        let mask = 1_u16 << reg;
        let was_set = (self.registers & mask) != 0;
        self.registers &= !mask;
        was_set
    }

    #[inline]
    fn add_stack(&mut self, slot: usize) {
        self.stack |= 1_u64 << slot;
    }

    #[inline]
    fn remove_stack(&mut self, slot: usize) -> bool {
        let mask = 1_u64 << slot;
        let was_set = (self.stack & mask) != 0;
        self.stack &= !mask;
        was_set
    }

    #[inline]
    fn add_stack_range(&mut self, start: usize, end: usize) {
        if end > start {
            let count = end - start;
            let mask = if count >= 64 { !0 } else { ((1_u64 << count) - 1) << start };
            self.stack |= mask;
        }
    }

    fn merge(self, other: Self) -> Self {
        Self { registers: self.registers | other.registers, stack: self.stack | other.stack }
    }

    fn alu(&mut self, dst: Register, src: Source) -> Result<(), VerifierErrorKind> {
        // Only do something if the dst is read, otherwise the computation doesn't matter.
        if self.has_reg(dst) {
            if let Source::Reg(src) = src {
                self.add_reg(src);
            }
        }
        Ok(())
    }

    fn jmp(&mut self, dst: Register, src: Source) -> Result<(), VerifierErrorKind> {
        self.add_reg(dst);
        if let Source::Reg(src) = src {
            self.add_reg(src);
        }
        Ok(())
    }

    fn atomic(
        &mut self,
        context: &ComputationContext,
        dst: Register,
        offset: i16,
        src: Register,
        is_cmpxchg: bool,
    ) -> Result<(), VerifierErrorKind> {
        let reg = context.reg(dst)?;
        let addr = reg.inner(context)?;
        if let Type::PtrToStack { offset: stack_offset } = *addr {
            let stack_offset = stack_offset.add(offset);
            stack_offset.check_valid_offset()?;
            let slot = stack_offset.array_index();
            self.add_stack(slot);
        }
        if is_cmpxchg {
            self.add_reg(0);
        }
        self.add_reg(src);
        self.add_reg(dst);
        Ok(())
    }
}

