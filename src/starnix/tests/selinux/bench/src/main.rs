fn compute_access_decision_bench(
    group: &mut criterion::BenchmarkGroup<'_, WallTime>,
    name_suffix: &'static str,
    source_context: &'static [u8],
    target_context: &'static [u8],
) {
    let server = new_populated_security_server();
    let source_sid = server.security_context_to_sid(source_context.into()).unwrap();
    let target_sid = server.security_context_to_sid(target_context.into()).unwrap();
    let class_id = server.class_id_by_name("file").unwrap();
    assert_ne!(source_sid, target_sid, "source and target contexts must resolve to distinct SIDs");
    assert_ne!(
        server.compute_access_decision_raw(source_sid, target_sid, class_id).allow,
        AccessVector::NONE,
        "source and target must match an allow rule"
    );

    let _ = group.bench_function(format!("compute_access_decision_{name_suffix}"), move |bench| {
        bench.iter(|| {
            let _ = black_box(server.compute_access_decision_raw(source_sid, target_sid, class_id));
        })
    });
}

fn compute_create_sid_bench(
    group: &mut criterion::BenchmarkGroup<'_, WallTime>,
    name_suffix: &'static str,
    source_context: &'static [u8],
    target_context: &'static [u8],
) {
    let server = new_populated_security_server();
    let source_sid = server.security_context_to_sid(source_context.into()).unwrap();
    let target_sid = server.security_context_to_sid(target_context.into()).unwrap();
    let class_id = server.class_id_by_name("process").unwrap();
    let created_sid =
        server.compute_create_sid_raw(source_sid, target_sid, class_id, /* name = */ &[]).unwrap();
    assert_ne!(created_sid, source_sid, "source and target must match a `type_transition` rule");
    assert_ne!(created_sid, target_sid, "new process must not inherit the target's label");

    let _ = group.bench_function(format!("compute_create_sid_{name_suffix}"), move |bench| {
        bench.iter(|| {
            let _ = black_box(
                server
                    .compute_create_sid_raw(source_sid, target_sid, class_id, /* name = */ &[])
                    .unwrap(),
            );
        })
    });
}

fn cached_create_sid_filename_bench(
    group: &mut criterion::BenchmarkGroup<'_, WallTime>,
    bench_name: &'static str,
    source_context: &'static [u8],
    target_context: &'static [u8],
    target_class: KernelClass,
    filename: &'static [u8],
) {
    let server = new_populated_security_server();
    let source_sid = server.security_context_to_sid(source_context.into()).unwrap();
    let target_sid = server.security_context_to_sid(target_context.into()).unwrap();
    let local_cache = PerThreadCache::default();
    let permission_check = server.as_permission_check(&local_cache);
    let nameless_sid = permission_check
        .compute_create_sid(source_sid, target_sid, target_class, /* name = */ &[])
        .unwrap();
    let created_sid = permission_check
        .compute_create_sid(source_sid, target_sid, target_class, filename)
        .unwrap();
    if bench_name == "match" {
        assert_ne!(created_sid, nameless_sid, "`match` must hit a filename transition rule");
    } else {
        assert_eq!(
            created_sid, nameless_sid,
            "`{bench_name}` must not hit a filename transition rule"
        );
    }

    let _ =
        group.bench_function(format!("cached_create_sid_filename_{bench_name}"), move |bench| {
            let permission_check = server.as_permission_check(&local_cache);
            bench.iter(|| {
                let _ = black_box(
                    permission_check
                        .compute_create_sid(source_sid, target_sid, target_class, filename)
                        .unwrap(),
                );
            })
        });
}

