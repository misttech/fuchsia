const POLICY_BYTES: &[u8] =
    include_bytes!("../../../../lib/selinux/testdata/policies/aosp_sepolicy");

/// Number of dynamic SIDs minted in [`populate_sid_table`] to give the `SidTable` a realistic
/// size prior to running benchmarks.
const POPULATED_SID_TABLE_SIZE: u32 = 1024;

/// Returns `base_context` with four MCS categories appended by mapping the four octets of `id`
/// (from lowest- to highest-order) into `c0..c255`, `c256..c511`, `c512..c767`, and `c768..c1023`.
///
/// `base_context` must have a single sensitivity and no categories, e.g. `"u:r:kernel:s0"`.
fn context_with_category_id(base_context: &str, id: u32) -> String {
    let [b0, b1, b2, b3] = id.to_le_bytes();
    format!(
        "{base_context}:c{},c{},c{},c{}",
        u16::from(b0),
        256 + u16::from(b1),
        512 + u16::from(b2),
        768 + u16::from(b3),
    )
}

/// Pre-populates `server`'s `SidTable` with [`POPULATED_SID_TABLE_SIZE`] dynamic SIDs generated by
/// encoding unique 32-bit values into four MCS categories (`c0..c1023`).
fn populate_sid_table(server: &SecurityServer) {
    for id in 0..POPULATED_SID_TABLE_SIZE {
        let context = context_with_category_id("u:r:kernel:s0", id);
        let _ = server.security_context_to_sid(context.as_bytes().into()).unwrap();
    }
}

/// Creates a [`SecurityServer`] with `aosp_sepolicy` loaded and [`populate_sid_table`] applied.
fn new_populated_security_server() -> Arc<SecurityServer> {
    let server = SecurityServer::new_default();
    let _ = server.load_policy(POLICY_BYTES.to_vec()).unwrap();
    populate_sid_table(&server);
    server
}

/// Pins the calling thread to the big CPU cores when built for VIM3 (`board_is_vim3`).
///
/// On VIM3s, set the thread affinity to big cores in order to reduce variation in the results.
/// This works around the scheduler's current behaviour. While the scheduler is set up to prefer
/// scheduling threads on big cores, benchmark and contention worker threads get scheduled on little
/// cores often enough that it reduces the usefulness of the performance results.
// TODO(https://fxbug.dev/42050716): Find a better way of controlling what cores are used for
// benchmarking and potentially benchmark both big and little cores.
fn pin_thread_to_big_cores() {
    if cfg!(board_is_vim3) {
        fuchsia_scheduler::set_role_for_this_thread(
            "fuchsia.microbenchmarks.pin_to_vim3_big_cores",
        )
        .expect("pin thread to VIM3 big cores");
    }
}

async fn spawn_test_kernel<F>(callback: F)
where
    F: AsyncFnOnce(&mut CurrentTask, &Arc<SecurityServer>) + Send + Sync + 'static,
{
    spawn_kernel_with_selinux_and_run(async |current_task, security_server| {
        pin_thread_to_big_cores();
        security_server.load_policy(POLICY_BYTES.to_vec()).unwrap();
        // Hooks skip all SELinux checks until the kernel is notified that a policy was loaded.
        security::selinuxfs_policy_loaded(current_task);
        // Enforce the policy, so that benchmarks fail on unexpected denials, rather than measure
        // their audit logging.
        security_server.set_enforcing(true);
        populate_sid_table(security_server);
        callback(current_task, security_server).await
    })
    .await;
}

fn create_file_bench(
    group: &mut criterion::BenchmarkGroup<'_, WallTime>,
    name: &'static str,
    current_task: &'static CurrentTask,
    hook_closure: impl Fn(&CurrentTask, &starnix_core::vfs::FileObject) + Send + Sync + 'static,
) {
    let file = Arc::new(PanickingFile::new_file(current_task));

    let _ = group.bench_function(name, move |bench| {
        let file = file.clone();
        bench.iter(|| {
            hook_closure(current_task, &file);
        })
    });
}

fn load_policy_bench(group: &mut criterion::BenchmarkGroup<'_, WallTime>) {
    let _ = group.bench_function("load_policy", move |bench| {
        bench.iter(|| {
            let server = SecurityServer::new_default();
            let _ = black_box(server.load_policy(POLICY_BYTES.to_vec()));
        })
    });
}

