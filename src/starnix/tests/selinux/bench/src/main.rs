fn binder_transaction_bench(
    group: &mut criterion::BenchmarkGroup<'_, WallTime>,
    current_task: &'static CurrentTask,
    security_server: &SecurityServer,
) {
    // `aosp_sepolicy` does not allow `kernel` to make Binder calls to itself, but allows calls to
    // `su`.
    let target_sid = security_server.security_context_to_sid(b"u:r:su:s0".into()).unwrap();
    let _ = group.bench_function("binder_transaction", move |bench| {
        let source_creds = current_task.current_creds();
        let mut target_creds = Credentials::clone(&source_creds);
        target_creds.security_state.current_sid = target_sid;
        bench.iter(|| {
            let _ = black_box(
                security::binder_transaction(current_task, &source_creds, &target_creds).unwrap(),
            );
        })
    });
}

fn main() {
    let mut executor = fuchsia_async::LocalExecutor::default();
    executor.run_singlethreaded(spawn_test_kernel(async move |current_task, security_server| {
        // SAFETY: The Criterion benchmarks run synchronously and block until completion
        // entirely within the scope of this closure. Therefore, `current_task` is guaranteed
        // to outlive the benchmark execution, making it safe to cast to a `'static` reference.
        let current_task = unsafe { &*(current_task as *const CurrentTask) };

        // List of benchmark programs is passed as the argument list from the
        // component manifest. The arguments passed by the test executor are
        // separated from the arguments in the manifest file by adding "--" at
        // the end of the argument list in the manifest file.
        let mut args: Vec<_> = std::env::args().collect();
        let Some(separator_pos) = args.iter().position(|arg| arg == "--") else {
            eprintln!("{:?}\n-- not found in the argument list", args);
            std::process::exit(1);
        };

        // Replace separator with the program name.
        args[separator_pos] = args[0].clone();

        let benchmark_args: Vec<_> = args[separator_pos..].iter().map(|arg| &**arg).collect();

        let mut fuchsia_criterion = FuchsiaCriterion::fuchsia_bench_with_args(&benchmark_args);
        let criterion: &mut Criterion = &mut fuchsia_criterion;

        *criterion = std::mem::take(criterion)
            .warm_up_time(Duration::from_millis(100))
            .measurement_time(Duration::from_secs(1))
            .sample_size(50);

        let mut group = criterion.benchmark_group("fuchsia.sestarnix");
        load_policy_bench(&mut group);
        security_context_to_sid_bench(&mut group, "simple", b"u:r:kernel:s0");
        security_context_to_sid_bench(&mut group, "c0_c255", b"u:r:kernel:s0:c0.c255");
        sid_to_security_context_bench(&mut group, "simple", b"u:r:kernel:s0");
        sid_to_security_context_bench(&mut group, "c0_c255", b"u:r:kernel:s0:c0.c255");
        compute_access_decision_bench(
            &mut group,
            "simple",
            b"u:r:untrusted_app:s0",
            b"u:object_r:app_data_file:s0",
        );
        compute_access_decision_bench(
            &mut group,
            "c0_c255",
            b"u:r:untrusted_app:s0:c0.c255",
            b"u:object_r:app_data_file:s0:c0.c255",
        );
        compute_create_sid_bench(
            &mut group,
            "simple",
            b"u:r:kernel:s0",
            b"u:object_r:init_exec:s0",
        );
        compute_create_sid_bench(
            &mut group,
            "c0_c255",
            b"u:r:kernel:s0:c0.c255",
            b"u:object_r:init_exec:s0:c0.c255",
        );
        // `system_data_file` has filename transition rules (`ndebugsocket` on `sock_file`), while
        // `tmpfs` has no filename transition rules (`no_target_rules`).
        let filename_transition_cases: &[(&str, &[u8], &[u8], KernelClass, &[u8])] = &[
            (
                "match",
                b"u:r:system_server:s0",
                b"u:object_r:system_data_file:s0",
                KernelClass::SockFile,
                b"ndebugsocket",
            ),
            (
                "no_match",
                b"u:r:system_server:s0",
                b"u:object_r:system_data_file:s0",
                KernelClass::SockFile,
                b"unlikely_filename_1234",
            ),
            (
                "no_target_rules",
                b"u:r:init:s0",
                b"u:object_r:tmpfs:s0",
                KernelClass::File,
                b"unlikely_filename_1234",
            ),
            ("nameless", b"u:r:init:s0", b"u:object_r:tmpfs:s0", KernelClass::File, b""),
        ];
        for &(bench_name, source, target, target_class, filename) in filename_transition_cases {
            compute_create_sid_filename_bench(
                &mut group,
                bench_name,
                source,
                target,
                target_class,
                filename,
            );
            cached_create_sid_filename_bench(
                &mut group,
                bench_name,
                source,
                target,
                target_class,
                filename,
            );
        }
        concurrent_access_cache_get_bench(&mut group);
        contention::register_benchmarks(&mut group);
        file_permission_bench(&mut group, current_task);
        fs_node_permission_bench(&mut group, current_task);
        check_file_ioctl_access_bench(&mut group, current_task);
        binder_transaction_bench(&mut group, current_task, security_server);
        group.finish();
    }));
}
