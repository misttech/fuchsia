    #[test]
    fn test_sharded_spill_and_refill() {
        let (storage, [mut writer0, mut writer1]) = TestStorage::new_sharded::<2>(NUM_NODES);

        // Helper to generate keys belonging to shard 0 or shard 1.
        let key_for_shard = |shard: usize, i: usize| -> AllocationKey<2> {
            let addr = ((i * 2 + shard) as u64) << 4;
            let key = AllocationKey::make(addr);
            assert_eq!(key.shard_index, shard);
            key
        };

        // Exhaust all `NUM_NODES` nodes on shard 0.
        for i in 0..NUM_NODES {
            assert_eq!(
                writer0.insert_allocation(
                    key_for_shard(0, i),
                    1,
                    THREAD_INFO_RESOURCE_KEY_1,
                    STACK_TRACE_RESOURCE_KEY_1,
                    zx::MonotonicInstant::ZERO,
                ),
                Ok(true)
            );
        }

        // Shard 1 cannot allocate yet because watermark is at NUM_NODES and nothing was spilled.
        assert_eq!(
            writer1.insert_allocation(
                key_for_shard(1, 0),
                1,
                THREAD_INFO_RESOURCE_KEY_1,
                STACK_TRACE_RESOURCE_KEY_1,
                zx::MonotonicInstant::ZERO,
            ),
            Err(crate::Error::OutOfSpace)
        );

        // Free `LOCAL_CACHE_CAPACITY + 1` nodes on shard 0 to trigger a spill of
        // `REFILL_SPILL_BATCH` nodes to the shared free list.
        for i in 0..(LOCAL_CACHE_CAPACITY + 1) {
            assert_eq!(writer0.erase_allocation(key_for_shard(0, i)), Some(1));
        }

        // Shard 1 can now allocate `REFILL_SPILL_BATCH` nodes from the shared free list.
        for i in 0..REFILL_SPILL_BATCH {
            assert_eq!(
                writer1.insert_allocation(
                    key_for_shard(1, i),
                    2,
                    THREAD_INFO_RESOURCE_KEY_2,
                    STACK_TRACE_RESOURCE_KEY_2,
                    zx::MonotonicInstant::ZERO,
                ),
                Ok(true)
            );
        }

        let reader = storage.create_reader();
        assert_eq!(
            reader.iter().count(),
            NUM_NODES - (LOCAL_CACHE_CAPACITY + 1) + REFILL_SPILL_BATCH
        );
    }
