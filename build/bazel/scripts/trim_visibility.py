def _describe_consumers(
    labels: Sequence[Label], graphs: dict[Label, set[str]], verbose: bool
) -> str:
    shown = labels if verbose else labels[:_MAX_EXAMPLES]
    parts = [f"{label} [{'+'.join(sorted(graphs[label]))}]" for label in shown]
    if len(labels) > len(shown):
        parts.append(f"... ({len(labels) - len(shown)} more)")
    return "\n         ".join(parts)


def _gn_load_note(path: str, gn_loaded: set[str] | None) -> str:
    if gn_loaded is not None and is_gn_file(path) and path not in gn_loaded:
        return "  (not loaded by the current GN build)"
    return ""


def print_list_report(
    title: str,
    report: ListReport,
    graphs: dict[Label, set[str]],
    gn_loaded: set[str] | None,
    verbose: bool,
) -> None:
    print(f"\n=== {title} ===")
    by_status: dict[Status, list[EntryReport]] = {s: [] for s in Status}
    for entry in report.entries:
        by_status[entry.status].append(entry)

    def header(status: Status, description: str) -> list[EntryReport]:
        entries = by_status[status]
        if entries:
            print(f"\n{description} ({len(entries)}):")
        return entries

    for e in header(Status.NEEDED, "Needed"):
        print(f'  "{e.text}"')
        print(f"      <- {_describe_consumers(e.consumers, graphs, verbose)}")
    for e in header(
        Status.UNVERIFIED,
        "Unverified, kept: no consumer in the analyzed graphs, but some "
        "consumers may be missing from them (check by hand)",
    ):
        print(f'  "{e.text}"')
        if e.reason:
            print(f"      ! {e.reason}")
        for path in e.text_references if verbose else e.text_references[:3]:
            print(f"      ~ {path}{_gn_load_note(path, gn_loaded)}")
    for e in header(Status.UNKNOWN, "Unknown, kept"):
        print(f'  "{e.text}"  ({e.reason})')
    for e in header(Status.REDUNDANT, "Redundant, remove"):
        print(f'  "{e.text}"  (covered by {e.subsumed_by})')
    for e in header(Status.UNUSED, "Unused, remove"):
        print(f'  "{e.text}"')
    if report.undetermined:
        print(
            f"\nConsumers covered only through unresolved package groups "
            f"({len(report.undetermined)}):"
        )
        for label in report.undetermined:
            print(f"  {label} [{'+'.join(sorted(graphs[label]))}]")
    if report.uncovered:
        print(
            f"\nWARNING: consumers NOT covered by the current list "
            f"({len(report.uncovered)}); visibility would reject them:"
        )
        for label in report.uncovered:
            print(f"  {label} [{'+'.join(sorted(graphs[label]))}]")
    if report.uncovered_references:
        print(
            f"\nBuild files that reference the target but are NOT covered by "
            f"the current list ({len(report.uncovered_references)}): dead "
            f"code, code not built by this configuration (a latent visibility "
            f"error), or false positives such as comments or other targets' "
            f"visibility lists:"
        )
        for path in report.uncovered_references:
            print(f"  ~ {path}{_gn_load_note(path, gn_loaded)}")


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--target",
        required=True,
        help="Label of the target with the visibility list, e.g. //foo:bar",
    )
    graph = parser.add_mutually_exclusive_group()
    graph.add_argument(
        "--bazel-only",
        action="store_true",
        help="Only consider the Bazel target and Bazel consumers.",
    )
    graph.add_argument(
        "--gn-only",
        action="store_true",
        help="Only consider the GN target and GN consumers.",
    )
    parser.add_argument(
        "--bazel-universe",
        default="//...",
        help="Query expression for the targets to search Bazel consumers in. "
        "Default: %(default)s",
    )
    parser.add_argument(
        "--no-text-search",
        action="store_true",
        help="Do not search for textual references to the target for entries "
        "that cover no consumer in the analyzed graphs.",
    )
    parser.add_argument(
        "--build-dir", help="Fuchsia build directory. Default: fx get-build-dir"
    )
    parser.add_argument(
        "--fuchsia-dir",
        default=os.environ.get(
            "FUCHSIA_DIR",
            os.path.join(
                os.path.dirname(os.path.abspath(__file__)), "../../.."
            ),
        ),
        help="Fuchsia source directory. Default: $FUCHSIA_DIR",
    )
    parser.add_argument(
        "--verbose",
        action="store_true",
        help="Print commands and all consumers per entry.",
    )
    args = parser.parse_args(argv)

    try:
        target = parse_label(args.target)
    except ValueError as e:
        parser.error(str(e))
    own = target.package
    fuchsia_dir = os.path.abspath(args.fuchsia_dir)
    tools = Tools(fuchsia_dir, args.build_dir, args.verbose)

    print(f"Analyzing {target} ...", file=sys.stderr)
    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as executor:
        bazel_future = (
            None
            if args.gn_only
            else executor.submit(
                collect_bazel, tools, target, args.bazel_universe
            )
        )
        gn_future = (
            None
            if args.bazel_only
            else executor.submit(collect_gn, tools, target)
        )
        bazel = bazel_future.result() if bazel_future else BazelData()
        gn = gn_future.result() if gn_future else GnData()

    if bazel.info is None and gn.visibility is None:
        raise Error(f"Found neither a Bazel nor a GN target for {target}.")

    def read(path: str) -> str | None:
        try:
            with open(os.path.join(fuchsia_dir, path)) as f:
                return f.read()
        except OSError:
            return None

    source = None
    if bazel.info is not None:
        build_text = read(os.path.join(own, "BUILD.bazel")) or read(
            os.path.join(own, "BUILD")
        )
        if build_text is not None:
            source = parse_source_visibility(
                build_text, bazel.info.generator_name or target.name
            )
    gn_generated = False
    if gn.visibility is not None:
        gn_generated = gn_target_is_generated_by_bazel2gn(
            read(os.path.join(own, "BUILD.gn")) or "", target.name
        )

    graphs: dict[Label, set[str]] = {}
    for label in bazel.consumers:
        graphs.setdefault(label, set()).add(GRAPH_BAZEL)
    for label in gn.consumers:
        graphs.setdefault(label, set()).add(GRAPH_GN)

    gn_loaded = tools.gn_loaded_build_files()
    reference_files: list[str] = []
    if not args.no_text_search:
        reference_files = [
            f
            for f in tools.git_grep_files(
                label_reference_regex(target),
                GN_BUILD_FILES + BAZEL_BUILD_FILES,
            )
            if build_file_package(f) != own
        ]

    def first_unloaded_build_gn(entry: Entry) -> str | None:
        """A BUILD.gn file in the scope of `entry` that GN did not load."""
        assert gn_loaded is not None
        if entry.kind != Kind.SUBPACKAGES:
            path = os.path.join(entry.package, "BUILD.gn")
            exists = os.path.exists(os.path.join(fuchsia_dir, path))
            return path if exists and path not in gn_loaded else None
        # Walk the file system rather than `git ls-files`, so that files in
        # git submodules (e.g. under //third_party) are found too.
        root = os.path.join(fuchsia_dir, entry.package)
        for directory, subdirs, files in os.walk(root):
            subdirs[:] = sorted(d for d in subdirs if not d.startswith("."))
            if "BUILD.gn" in files:
                path = os.path.relpath(
                    os.path.join(directory, "BUILD.gn"), fuchsia_dir
                )
                if path not in gn_loaded:
                    return path
        return None

    def check_unused(entry: Entry) -> tuple[Status, str] | None:
        """Keeps entries whose packages may hide consumers from the graphs."""
        if entry.kind not in (Kind.PACKAGE, Kind.SUBPACKAGES, Kind.TARGET):
            return None
        if not entry.package:
            return None
        if tools.git_is_untracked_and_ignored(entry.package):
            # E.g. //vendor/...: another repository, or not checked out.
            return Status.UNKNOWN, (
                f"//{entry.package} is not part of fuchsia.git, so it was "
                "not searched"
            )
        if not os.path.isdir(os.path.join(fuchsia_dir, entry.package)):
            return None
        if gn_loaded is None:
            return None
        unloaded = first_unloaded_build_gn(entry)
        if unloaded is None:
            return None
        return Status.UNVERIFIED, (
            f"{unloaded} is not loaded by the current GN build"
        )

    # Describe the target.
    print(f"\nTarget: {target}")
    if bazel.info is not None:
        print(f"  Bazel: {bazel.info.kind}")
    elif not args.gn_only:
        print("  Bazel: no target")
    if gn.visibility is not None:
        how = "generated by bazel2gn" if gn_generated else "hand-written"
        print(f"  GN: {how}, in {len(gn.instances)} toolchain(s)")
    elif not args.bazel_only:
        print("  GN: no target in the current build graph")
    if not args.gn_only:
        errors = (
            f", ignored {bazel.query_errors} errors from packages that failed "
            "to load (--keep_going; use --verbose to see the commands)"
            if bazel.query_errors
            else ""
        )
        print(
            f"  Bazel consumers: {len(bazel.consumers)} "
            f"(rdeps in {args.bazel_universe}{errors})"
        )
    if not args.bazel_only:
        print(
            f"  GN consumers: {len(gn.consumers)} "
            f"(gn refs in {os.path.relpath(tools.build_dir, fuchsia_dir)})"
        )

    # The Bazel list, as written by the user.
    bazel_entries: list[str] | None = None
    bazel_implicit: list[Entry] = [Entry(Kind.PACKAGE, own)]
    if bazel.info is not None:
        effective = bazel.info.visibility
        if effective is None or (source is not None and not source.present):
            print(
                "\nThe Bazel target does not set `visibility`; it uses the "
                "package's default_visibility. Nothing to trim."
            )
        elif source is not None and source.entries is not None:
            bazel_entries = source.entries
            written = {parse_bazel_entry(t, own) for t in bazel_entries}
            for text in effective:
                entry = parse_bazel_entry(text, own)
                if entry not in written and entry not in bazel_implicit:
                    bazel_implicit.append(entry)
        else:
            print(
                "\nWARNING: could not statically resolve `visibility` in "
                "BUILD.bazel; using the effective value from `bazel query`, "
                "which may include entries added by macros."
            )
            bazel_entries = effective
        added = [
            text
            for text in (entry_to_bazel(e, own) for e in bazel_implicit[1:])
            if text is not None
        ]
        if added:
            print(
                "\nNote: entries added by a macro, ignored: "
                + ", ".join(f'"{a}"' for a in added)
            )

    overwrites = source.overwrites if source is not None else []
    split = False
    if bazel_entries is not None and gn.visibility is not None:
        if not gn_generated:
            split = True
            print(
                "\nNote: the GN target is hand-written, so the Bazel and GN "
                "lists are trimmed separately."
            )
        elif overwrites:
            split = True
            print(
                "\nNote: `visibility` has bazel2gn overwrite annotations ("
                + "; ".join(overwrites)
                + "), so the Bazel list is checked against Bazel consumers "
                "only, and the GN list against GN consumers only."
            )
        else:
            expected = expected_gn_entries(
                [parse_bazel_entry(t, own) for t in bazel_entries], own
            )
            actual = {parse_gn_entry(t, own) for t in gn.visibility}
            if expected != actual | {Entry(Kind.PACKAGE, own)}:
                split = True
                print(
                    "\nWARNING: the GN visibility differs from the Bazel one "
                    "and there is no bazel2gn overwrite annotation. Is the "
                    "BUILD.gn stale (run `fx bazel2gn`)? Trimming the lists "
                    "separately."
                )

    if bazel_entries is not None:
        bazel_consumers_only = split or gn.visibility is None
        if bazel_consumers_only:
            consumers = bazel.consumers
            title = "BUILD.bazel visibility (checked against Bazel consumers)"
        else:
            consumers = bazel.consumers | gn.consumers
            title = (
                "BUILD.bazel visibility (checked against Bazel and GN "
                "consumers, as bazel2gn derives the GN list from it)"
            )

        def check_unused_bazel(entry: Entry) -> tuple[Status, str] | None:
            result = check_unused(entry)
            # Unloaded BUILD.gn files only matter for GN consumers.
            if (
                bazel_consumers_only
                and result
                and result[0] == Status.UNVERIFIED
            ):
                return None
            return result

        report = analyze_list(
            bazel_entries,
            parse_bazel_entry,
            own,
            consumers,
            implicit_entries=bazel_implicit,
            groups=bazel.groups,
            reference_files=[
                f
                for f in reference_files
                if not bazel_consumers_only or not is_gn_file(f)
            ],
            check_unused=check_unused_bazel,
            macro_locations=bazel.macro_locations,
        )
        print_list_report(title, report, graphs, gn_loaded, args.verbose)
        kept = [e.text for e in report.kept()]
        print("\nTrimmed list for BUILD.bazel:\n")
        print(format_bazel_list(kept))

    if gn.visibility is not None and (split or bazel_entries is None):
        gn_list = gn.visibility
        report = analyze_list(
            gn_list,
            parse_gn_entry,
            own,
            gn.consumers,
            reference_files=[f for f in reference_files if is_gn_file(f)],
            check_unused=check_unused,
        )
        print_list_report(
            "GN visibility, from `gn desc` (checked against GN consumers)",
            report,
            graphs,
            gn_loaded,
            args.verbose,
        )
        kept_entries = report.kept()
        kept_gn = [entry_to_gn(e.entry, own) for e in kept_entries]
        if split and gn_generated:
            print("\nTrimmed GN list, for the bazel2gn annotation:\n")
            print(format_bazel2gn_overwrite(kept_gn))
        else:
            print("\nTrimmed list for BUILD.gn:\n")
            print(format_gn_list(kept_gn))
        if bazel.info is None:
            print(
                "\nBazel equivalent, for when the target is migrated "
                "(single-target entries are widened to their package):\n"
            )
            print(
                format_bazel_list(
                    gn_list_to_bazel([e.entry for e in kept_entries], own)
                )
            )
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Error as e:
        print(f"ERROR: {e}", file=sys.stderr)
        sys.exit(1)
