class Tools:
    """Runs fx, gn, bazel and git commands in a Fuchsia checkout."""

    def __init__(self, fuchsia_dir: str, build_dir: str | None, verbose: bool):
        self.fuchsia_dir = fuchsia_dir
        self.verbose = verbose
        fx = os.path.join(fuchsia_dir, ".jiri_root", "bin", "fx")
        if not os.path.exists(fx):
            fx = shutil.which("fx") or os.path.join(
                fuchsia_dir, "scripts", "fx"
            )
        self.fx = fx
        self.build_dir = build_dir or self._get_build_dir()

    def log(self, message: str) -> None:
        if self.verbose:
            print(message, file=sys.stderr)

    def run(
        self, command: list[str], check: bool = True
    ) -> subprocess.CompletedProcess[str]:
        self.log("+ " + " ".join(command))
        result = subprocess.run(
            command,
            cwd=self.fuchsia_dir,
            capture_output=True,
            text=True,
        )
        if check and result.returncode != 0:
            raise Error(
                f"Command failed ({result.returncode}): {' '.join(command)}\n"
                f"{result.stderr[-4000:]}"
            )
        return result

    def _get_build_dir(self) -> str:
        build_dir = self.run([self.fx, "get-build-dir"]).stdout.strip()
        if not build_dir or not os.path.isdir(build_dir):
            raise Error("No build directory, run `fx set` first.")
        return build_dir

    def gn(
        self, args: list[str], check: bool = True
    ) -> subprocess.CompletedProcess[str]:
        return self.run(
            [self.fx, "gn", args[0], self.build_dir] + args[1:], check=check
        )

    def bazel_query(
        self, args: list[str], check: bool = True
    ) -> subprocess.CompletedProcess[str]:
        return self.run([self.fx, "bazel", "query"] + args, check=check)

    def git_grep_files(self, regex: str, pathspecs: Sequence[str]) -> list[str]:
        if not pathspecs:
            return []
        result = self.run(
            ["git", "grep", "-l", "-E", regex, "--"] + list(pathspecs),
            check=False,
        )
        if result.returncode not in (0, 1):
            raise Error(f"git grep failed: {result.stderr}")
        return result.stdout.splitlines()

    def git_is_untracked_and_ignored(self, path: str) -> bool:
        """Whether `path` is outside fuchsia.git, e.g. //vendor/...

        Git submodules are tracked, so they are not considered outside.
        """
        if self.run(["git", "ls-files", "--", path]).stdout.strip():
            return False
        result = self.run(
            ["git", "check-ignore", "-q", "--no-index", path + "/"],
            check=False,
        )
        return result.returncode == 0

    def gn_loaded_build_files(self) -> set[str] | None:
        """Source-relative paths of the GN files loaded by `gn gen`."""
        depfile = os.path.join(self.build_dir, "build.ninja.d")
        try:
            with open(depfile) as f:
                inputs = parse_ninja_depfile_inputs(f.read())
        except OSError:
            return None
        return {
            os.path.relpath(
                os.path.normpath(os.path.join(self.build_dir, path)),
                self.fuchsia_dir,
            )
            for path in inputs
        }


@dataclasses.dataclass
class BazelData:
    info: BazelRuleInfo | None = None
    consumers: set[Label] = dataclasses.field(default_factory=set)
    query_errors: int = 0
    groups: dict[Label, PackageGroup] = dataclasses.field(default_factory=dict)
    macro_locations: dict[Label, list[str]] = dataclasses.field(
        default_factory=dict
    )


@dataclasses.dataclass
class GnData:
    instances: list[str] = dataclasses.field(default_factory=list)
    visibility: list[str] | None = None
    consumers: set[Label] = dataclasses.field(default_factory=set)


def collect_bazel(tools: Tools, target: Label, universe: str) -> BazelData:
    data = BazelData()
    result = tools.bazel_query(["--output=build", str(target)], check=False)
    if result.returncode != 0:
        tools.log(f"No Bazel target {target}: {result.stderr.strip()[-500:]}")
        return data
    data.info = parse_bazel_build_output(result.stdout)
    if data.info is None:
        return data

    # Resolve package groups referenced by the visibility list.
    pending = []
    for text in data.info.visibility or []:
        entry = parse_bazel_entry(text, target.package)
        if entry.kind == Kind.PACKAGE_GROUP:
            pending.append(entry.label)
    while pending:
        label = pending.pop()
        if label in data.groups:
            continue
        group_result = tools.bazel_query(
            ["--output=build", str(label)], check=False
        )
        group = (
            parse_package_group_build_output(group_result.stdout)
            if group_result.returncode == 0
            else None
        )
        if group is not None:
            data.groups[label] = group
            pending.extend(group.includes)

    # --keep_going makes the query succeed with partial results (exit code 3)
    # when some packages in the universe fail to load.
    query = f"rdeps({universe}, {target}, 1)"
    result = tools.bazel_query(["--keep_going", query], check=False)
    if result.returncode not in (0, 3):
        raise Error(f"Bazel query failed: {query}\n{result.stderr[-4000:]}")
    data.query_errors = count_query_errors(result.stderr)
    if data.query_errors:
        tools.log(result.stderr[-4000:])
    data.consumers = parse_labels(result.stdout.splitlines()) - {target}

    # Find the macros that instantiated the consumers. The query is passed in
    # a file because the list of consumers can be long.
    if data.consumers:
        labels = " ".join(str(label) for label in sorted(data.consumers))
        with tempfile.NamedTemporaryFile(
            "w", prefix="trim_visibility_", suffix=".txt"
        ) as query_file:
            query_file.write(f"set({labels})")
            query_file.flush()
            result = tools.bazel_query(
                ["--output=build", f"--query_file={query_file.name}"],
                check=False,
            )
        if result.returncode == 0:
            data.macro_locations = parse_macro_locations(
                result.stdout, data.consumers
            )
        else:
            tools.log(f"Could not query consumers: {result.stderr[-2000:]}")
    return data


def collect_gn(tools: Tools, target: Label) -> GnData:
    data = GnData()
    # `gn ls` with a wildcard pattern matches all toolchains, and `gn desc`
    # in the default toolchain can run at the same time.
    with concurrent.futures.ThreadPoolExecutor(max_workers=2) as executor:
        ls_future = executor.submit(
            tools.gn, ["ls", f"//{target.package}:*"], False
        )
        desc_future = executor.submit(
            tools.gn, ["desc", str(target), "visibility"], False
        )
        ls_result = ls_future.result()
        desc_result = desc_future.result()
    if ls_result.returncode == 0:
        data.instances = parse_gn_instances(ls_result.stdout, target)
    if not data.instances and desc_result.returncode == 0:
        # `gn ls` does not list configs, but `gn desc` and `gn refs` work.
        data.instances = [str(target)]
    if not data.instances:
        tools.log(f"No GN target {target}")
        return data
    if desc_result.returncode != 0:
        # The target is not defined in the default toolchain.
        desc_result = tools.gn(["desc", data.instances[0], "visibility"])
    data.visibility = [
        line.strip() for line in desc_result.stdout.splitlines() if line.strip()
    ]
    # Fully qualified labels so that all toolchains are covered.
    refs = tools.gn(["refs"] + data.instances)
    data.consumers = parse_labels(refs.stdout.splitlines()) - {target}
    return data


