_STRING_RE = re.compile(r'"((?:[^"\\]|\\.)*)"')


def _string_list_attr(build_output: str, attr: str) -> list[str] | None:
    """Extracts a string list attribute from `bazel query --output=build`."""
    match = re.search(
        rf"^\s*{re.escape(attr)} = \[(.*?)\]", build_output, re.MULTILINE
    )
    if match is None:
        return None
    return _STRING_RE.findall(match.group(1))


@dataclasses.dataclass
class BazelRuleInfo:
    kind: str
    # Effective visibility, including entries added by macros. None if the
    # rule does not set it explicitly.
    visibility: list[str] | None
    # Name of the target passed to the outermost macro, if any.
    generator_name: str | None


def parse_bazel_build_output(text: str) -> BazelRuleInfo | None:
    """Parses `bazel query --output=build` for a single rule."""
    kind_match = re.search(r"^(\w+)\($", text, re.MULTILINE)
    if kind_match is None:
        return None
    generator = re.search(r'^\s*generator_name = "([^"]*)"', text, re.MULTILINE)
    return BazelRuleInfo(
        kind=kind_match.group(1),
        visibility=_string_list_attr(text, "visibility"),
        generator_name=generator.group(1) if generator else None,
    )


def parse_package_group_build_output(text: str) -> PackageGroup | None:
    """Parses `bazel query --output=build` for a package_group."""
    info = parse_bazel_build_output(text)
    if info is None or info.kind != "package_group":
        return None
    includes = []
    for include in _string_list_attr(text, "includes") or []:
        try:
            includes.append(parse_label(include))
        except ValueError:
            pass
    return PackageGroup(_string_list_attr(text, "packages") or [], includes)


def parse_macro_locations(
    build_output: str, labels: Iterable[Label]
) -> dict[Label, list[str]]:
    """Finds the packages of the .bzl files that instantiated each rule.

    Args:
        build_output: `bazel query --output=build` for several rules.
        labels: The labels of these rules.

    Returns:
        For each rule instantiated by a macro defined in the main repository,
        the packages of the .bzl files in its instantiation stack, innermost
        last. Visibility of a dependency introduced by a symbolic macro is
        checked against the package that defines the macro, not against the
        package of the instantiated target.
    """
    by_name: dict[str, list[Label]] = {}
    for label in sorted(labels, key=lambda l: len(l.package), reverse=True):
        by_name.setdefault(label.name, []).append(label)
    result: dict[Label, list[str]] = {}
    build_dir: str | None = None
    current: Label | None = None
    workspace: str | None = None
    in_stack = False
    for line in build_output.splitlines():
        header = re.match(r"^# (/\S+)/BUILD(?:\.bazel)?:\d+:\d+$", line)
        if header:
            build_dir = header.group(1)
            current = None
            workspace = None
            in_stack = False
            continue
        name = re.match(r'^  name = "([^"]*)",$', line)
        if name and build_dir is not None and current is None:
            for label in by_name.get(name.group(1), []):
                suffix = "/" + label.package if label.package else ""
                if build_dir.endswith(suffix):
                    current = label
                    workspace = build_dir[: len(build_dir) - len(suffix)]
                    break
            continue
        if re.match(r"^# Rule \S+ instantiated at", line):
            in_stack = True
            continue
        if re.match(r"^# Rule \S+ defined at", line):
            in_stack = False
            continue
        frame = re.match(r"^#\s+(/\S+\.bzl):\d+:\d+\s+in ", line)
        if in_stack and frame and current is not None and workspace:
            path = frame.group(1)
            if path.startswith(workspace + "/"):
                package = os.path.dirname(path[len(workspace) + 1 :])
                locations = result.setdefault(current, [])
                if package not in locations:
                    locations.append(package)
    return result


@dataclasses.dataclass
class SourceVisibility:
    """The `visibility` attribute of a target as written in BUILD.bazel."""

    # Whether the target sets `visibility` explicitly.
    present: bool
    # The string values, or None if they could not be statically resolved.
    entries: list[str] | None = None
    # bazel2gn annotations that change the converted GN visibility, e.g.
    # `raw_overwrite:[ "//*" ]`.
    overwrites: list[str] = dataclasses.field(default_factory=list)


def _comment_annotations(lines: Sequence[str]) -> list[str]:
    annotations = []
    for line in lines:
        index = line.find("# " + BAZEL2GN_ANNOTATION)
        if index < 0:
            continue
        annotation = line[index + 2 + len(BAZEL2GN_ANNOTATION) :].strip()
        if not annotation.startswith(_NON_OVERWRITE_ANNOTATIONS):
            annotations.append(annotation)
    return annotations


def parse_source_visibility(
    build_text: str, target_name: str
) -> SourceVisibility | None:
    """Finds the `visibility` of `target_name` in a BUILD.bazel file.

    Returns None if the target or file could not be parsed. Starlark BUILD
    files are almost always valid Python syntax, so the `ast` module is used.
    """
    try:
        module = ast.parse(build_text)
    except SyntaxError:
        return None
    lines = build_text.splitlines()

    assignments: dict[str, ast.expr] = {}
    calls: list[ast.Call] = []
    for statement in module.body:
        if isinstance(statement, ast.Assign):
            for assign_target in statement.targets:
                if isinstance(assign_target, ast.Name):
                    assignments[assign_target.id] = statement.value
        elif isinstance(statement, ast.Expr) and isinstance(
            statement.value, ast.Call
        ):
            calls.append(statement.value)

    def keyword(call: ast.Call, name: str) -> ast.expr | None:
        for kw in call.keywords:
            if kw.arg == name:
                return kw.value
        return None

    call = None
    for candidate in calls:
        name = keyword(candidate, "name")
        if isinstance(name, ast.Constant) and name.value == target_name:
            call = candidate
            break
    if call is None:
        return None
    value = keyword(call, "visibility")
    if value is None:
        return SourceVisibility(present=False)

    overwrites: list[str] = []

    def node_lines(node: ast.expr) -> list[str]:
        end = node.end_lineno or node.lineno
        return lines[node.lineno - 1 : end]

    def resolve(node: ast.expr, depth: int = 0) -> list[str] | None:
        overwrites.extend(_comment_annotations(node_lines(node)))
        if depth > 10:
            return None
        if isinstance(node, ast.List):
            result = []
            for element in node.elts:
                if not isinstance(element, ast.Constant) or not isinstance(
                    element.value, str
                ):
                    return None
                result.append(element.value)
            return result
        if isinstance(node, ast.Name) and node.id in assignments:
            return resolve(assignments[node.id], depth + 1)
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
            left = resolve(node.left, depth + 1)
            right = resolve(node.right, depth + 1)
            if left is None or right is None:
                return None
            return left + right
        return None

    entries = resolve(value)
    return SourceVisibility(
        present=True, entries=entries, overwrites=sorted(set(overwrites))
    )


def gn_target_is_generated_by_bazel2gn(build_gn_text: str, name: str) -> bool:
    """Whether `name` is defined below the bazel2gn sentinel of a BUILD.gn."""
    _, sentinel, generated = build_gn_text.partition(BAZEL2GN_SENTINEL)
    if not sentinel:
        return False
    return re.search(rf'\(\s*"{re.escape(name)}"\s*\)', generated) is not None


def parse_gn_instances(gn_ls_output: str, target: Label) -> list[str]:
    """Selects `target`'s instances (in any toolchain) from `gn ls` output."""
    instances = []
    for line in gn_ls_output.splitlines():
        line = line.strip()
        if not line.startswith("//"):
            continue
        try:
            if parse_label(line) == target:
                instances.append(line)
        except ValueError:
            continue
    return instances


def parse_labels(lines: Iterable[str]) -> set[Label]:
    """Parses labels in the main repository, ignoring anything else."""
    labels = set()
    for line in lines:
        line = line.strip()
        if not line.startswith(("//", "@//", "@@//")):
            continue
        try:
            labels.add(parse_label(line))
        except ValueError:
            continue
    return labels


def count_query_errors(stderr: str) -> int:
    """Counts relevant errors in the output of `bazel query --keep_going`.

    References to `@gn_targets`, which is only populated by `fx build`, are
    expected and do not hide consumers, so they are not counted.
    """
    return sum(
        1
        for line in stderr.splitlines()
        if line.startswith("ERROR: ")
        and "@gn_targets" not in line
        and not line.startswith("ERROR: Evaluation of query")
    )


def parse_ninja_depfile_inputs(depfile_text: str) -> list[str]:
    """Returns the inputs listed in a depfile such as build.ninja.d."""
    _, _, inputs = depfile_text.partition(": ")
    return inputs.replace("\\\n", " ").split()


def ere_escape(text: str) -> str:
    """Escapes `text` for a POSIX extended regular expression."""
    return re.sub(r"([.\[\]()*+?{}|^$\\])", r"\\\1", text)


def label_reference_regex(target: Label) -> str:
    """An extended regex matching quoted references to `target`."""
    package = ere_escape("//" + target.package)
    name = ere_escape(target.name)
    if target.name == target.package.rpartition("/")[2]:
        return f'"{package}(:{name})?["(]'
    return f'"{package}:{name}["(]'


# Git pathspecs of the GN and Bazel build files.
GN_BUILD_FILES = ("*.gn", "*.gni")
BAZEL_BUILD_FILES = ("*BUILD.bazel", "*/BUILD", "*.bzl")


def is_gn_file(path: str) -> bool:
    return path.endswith((".gn", ".gni"))


# GN's `secondary_source` (see //.gn): GN loads
# build/secondary/<package>/BUILD.gn for packages that have no BUILD.gn of
# their own, e.g. //third_party/ogg.
GN_SECONDARY_SOURCE = "build/secondary/"


def build_file_package(path: str) -> str:
    """The package that a build file at `path` defines targets in."""
    package = os.path.dirname(path)
    if (
        package.startswith(GN_SECONDARY_SOURCE)
        and os.path.basename(path) == "BUILD.gn"
    ):
        return package[len(GN_SECONDARY_SOURCE) :]
    return package


def entry_covers_path(
    entry: Entry, path: str, groups: dict[Label, PackageGroup]
) -> bool | None:
    """Whether a build file at `path` belongs to a package `entry` covers.

    Returns None if this cannot be determined (unresolved package_group).
    """
    package = build_file_package(path)
    if entry.kind == Kind.TARGET:
        return entry.package == package
    return covers(entry, Label(package, "*"), groups)


