"""Trims the visibility allowlist of a Bazel, dual-built or GN target.

Example usage:
$ fx set ...
$ build/bazel/scripts/trim_visibility.py --target=//zircon/system/ulib/svc:svc

This is the Bazel-aware counterpart of scripts/gn/trim_visibility.py. It finds
the direct consumers of a target in both build graphs and reports, for each
entry of the target's visibility list, whether it is still needed:

  * Bazel consumers are the result of
    `fx bazel query --keep_going 'rdeps(<universe>, <target>, 1)'`.
    The universe defaults to `//...`. A dependency added by a symbolic macro
    is checked against the package that defines the macro, so consumers
    whose own package is not covered are also matched against the packages
    of the .bzl files that instantiated them.
  * GN consumers are the result of `fx gn refs <build_dir> <target>` for
    every toolchain the corresponding GN target is defined in. This is only
    done if a GN target with the same label exists, e.g. because it is
    generated by bazel2gn or because the target was not migrated yet.

The GN graph only contains the BUILD.gn files loaded by the current `fx set`
configuration. So an entry that covers no consumer is kept as "unverified" if
a build file in its scope references the target textually (`git grep`), or if
its scope contains BUILD.gn files that the current GN build does not load.
Build files that reference the target but are not covered by the list are
reported too: they are dead code, latent visibility errors, or false
positives.

Limitations:
  * A BUILD.gn file outside of the list that is not loaded by the current
    GN build and depends on the target only through a template is not
    reported (it would be a latent visibility error anyway).
  * `gn refs` does not report configs that reference a config through their
    own `configs`.
  * Entries for packages outside of fuchsia.git (e.g. //vendor/...) are
    kept as "unknown".
  * The textual search does not look into git submodules (e.g. most of
    //third_party); unused entries there are only kept if their BUILD.gn
    files are not loaded by the current GN build.

When the BUILD.bazel `visibility` attribute carries a bazel2gn overwrite
annotation (e.g. `# @bazel2gn:raw_overwrite:[ "//*" ]`), the Bazel and GN
lists are different on purpose: the Bazel list is checked against Bazel
consumers only, and the GN list (as reported by `fx gn desc`) against GN
consumers only.

The trimmed lists are printed in the syntax of the build file that contains
them: Bazel syntax (`//foo:__pkg__`, `//foo:__subpackages__`) for BUILD.bazel
and GN syntax (`//foo:*`, `//foo/*`) for BUILD.gn or bazel2gn annotations.
For GN-only targets, a Bazel equivalent is printed as well, for use when
migrating the target to Bazel.

To run this script's tests:
$ fx test //build/bazel/scripts:trim_visibility_test
"""

