@dataclasses.dataclass(frozen=True, order=True)
class Label:
    """A label in the main repository, e.g. //foo/bar:baz.

    `package` has no leading `//` and is empty for the root package.
    """

    package: str
    name: str

    def __str__(self) -> str:
        return f"//{self.package}:{self.name}"


def strip_toolchain(label: str) -> str:
    """Removes a GN toolchain suffix, e.g. `//foo:bar(//tc:x64)` -> `//foo:bar`."""
    if label.endswith(")") and "(" in label:
        return label[: label.index("(")]
    return label


def parse_label(text: str, current_package: str | None = None) -> Label:
    """Parses an absolute or package-relative Bazel or GN label.

    Raises:
        ValueError: if `text` is not a label in the main repository.
    """
    label = strip_toolchain(text.strip())
    # Canonical labels of the main repository, e.g. `@//foo` or `@@//foo`.
    if label.startswith("@@//"):
        label = label[2:]
    elif label.startswith("@//"):
        label = label[1:]
    if label.startswith("@"):
        raise ValueError(f"Not a label in the main repository: {text}")
    if label.startswith("//"):
        package, sep, name = label[2:].partition(":")
        package = package.rstrip("/")
        if package == ".":
            package = ""
        if not sep:
            name = package.rpartition("/")[2]
    elif label.startswith(":"):
        if current_package is None:
            raise ValueError(f"Relative label without a package: {text}")
        package, name = current_package, label[1:]
    else:
        raise ValueError(f"Not an absolute or relative label: {text}")
    if not name:
        raise ValueError(f"Invalid label: {text}")
    return Label(package, name)


def is_in_package_tree(package: str, root: str) -> bool:
    """Whether `package` is `root` or one of its subpackages."""
    return not root or package == root or package.startswith(root + "/")


