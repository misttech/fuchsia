@dataclasses.dataclass
class PackageGroup:
    packages: list[str]
    includes: list[Label]


def package_spec_matches(spec: str, package: str) -> bool:
    """Whether a package_group `packages` spec (without `-`) matches."""
    if spec in ("public", "//..."):
        return True
    if spec == "private":
        return False
    spec = spec.removeprefix("@").removeprefix("@")
    if not spec.startswith("//"):
        return False
    if spec.endswith("/..."):
        return is_in_package_tree(package, spec[2:-4])
    return package == spec[2:]


def package_group_contains(
    group_label: Label,
    package: str,
    groups: dict[Label, PackageGroup],
    _seen: frozenset[Label] = frozenset(),
) -> bool | None:
    """Whether the package_group `group_label` contains `package`.

    Returns None if the group, or a group it includes, could not be resolved.
    """
    group = groups.get(group_label)
    if group is None or group_label in _seen:
        return None
    positive = [s for s in group.packages if not s.startswith("-")]
    negative = [s[1:] for s in group.packages if s.startswith("-")]
    if any(package_spec_matches(s, package) for s in positive) and not any(
        package_spec_matches(s, package) for s in negative
    ):
        return True
    unknown = False
    for include in group.includes:
        result = package_group_contains(
            include, package, groups, _seen | {group_label}
        )
        if result:
            return True
        if result is None:
            unknown = True
    return None if unknown else False


def covers(
    entry: Entry, consumer: Label, groups: dict[Label, PackageGroup]
) -> bool | None:
    """Whether `entry` makes a target visible to `consumer`.

    Returns None if this cannot be determined (unresolved package_group).
    """
    if entry.kind == Kind.PUBLIC:
        return True
    if entry.kind == Kind.PRIVATE:
        return False
    if entry.kind == Kind.PACKAGE:
        return consumer.package == entry.package
    if entry.kind == Kind.SUBPACKAGES:
        return is_in_package_tree(consumer.package, entry.package)
    if entry.kind == Kind.TARGET:
        return consumer == entry.label
    return package_group_contains(entry.label, consumer.package, groups)


