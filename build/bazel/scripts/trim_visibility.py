class Status(enum.Enum):
    NEEDED = "needed"
    UNVERIFIED = "unverified"
    UNKNOWN = "unknown"
    REDUNDANT = "redundant"
    UNUSED = "unused"


@dataclasses.dataclass
class EntryReport:
    text: str
    entry: Entry
    status: Status = Status.UNUSED
    consumers: list[Label] = dataclasses.field(default_factory=list)
    text_references: list[str] = dataclasses.field(default_factory=list)
    subsumed_by: str | None = None
    # Why an UNVERIFIED or UNKNOWN entry is kept.
    reason: str | None = None


@dataclasses.dataclass
class ListReport:
    entries: list[EntryReport]
    # Consumers no entry covers. Unless visibility checks were bypassed, these
    # are not built in the current configuration or the analysis is wrong.
    uncovered: list[Label]
    # Consumers for which coverage depends on an unresolved package_group.
    undetermined: list[Label]
    # Build files that reference the target textually but are not covered by
    # the list: dead code, code not built by the current configuration (a
    # latent visibility error), or false positives such as comments.
    uncovered_references: list[str] = dataclasses.field(default_factory=list)

    def kept(self) -> list[EntryReport]:
        keep = (Status.NEEDED, Status.UNVERIFIED, Status.UNKNOWN)
        return [e for e in self.entries if e.status in keep]


def analyze_list(
    entry_texts: Sequence[str],
    parse_entry: Callable[[str, str], Entry],
    own_package: str,
    consumers: Iterable[Label],
    implicit_entries: Sequence[Entry] = (),
    groups: dict[Label, PackageGroup] | None = None,
    reference_files: Sequence[str] | None = None,
    check_unused: Callable[[Entry], tuple[Status, str] | None] | None = None,
    macro_locations: dict[Label, list[str]] | None = None,
) -> ListReport:
    """Classifies the entries of a visibility list.

    Args:
        entry_texts: The visibility list, as written.
        parse_entry: parse_bazel_entry or parse_gn_entry.
        own_package: The package of the target that has the visibility list.
        consumers: Direct consumers found in the build graph(s).
        implicit_entries: Entries that apply without being written in the
            list, e.g. Bazel's implicit own-package visibility or entries
            added by a macro. They are never reported or trimmed.
        groups: Resolved Bazel package groups.
        reference_files: Build files outside of the target's package that
            reference the target textually. Entries that cover no consumer
            but cover one of these files are kept as "unverified".
        check_unused: Called for entries that are still unused after the
            text search; can return another status and a reason, e.g. when
            the entry covers BUILD.gn files that are not part of the graph.
        macro_locations: For Bazel consumers instantiated by macros, the
            packages that define these macros. A consumer whose own package
            is not covered is matched against these packages instead.
    """
    groups = groups or {}
    reports = [EntryReport(t, parse_entry(t, own_package)) for t in entry_texts]
    uncovered: list[Label] = []
    undetermined: list[Label] = []
    macro_locations = macro_locations or {}
    for consumer in sorted(set(consumers)):
        # Try the consumer's package first, then the macro packages.
        locations = [consumer] + [
            Label(p, consumer.name) for p in macro_locations.get(consumer, [])
        ]
        found = False
        unknown = False
        for location in locations:
            if any(covers(e, location, groups) for e in implicit_entries):
                found = True
                break
            for report in reports:
                result = covers(report.entry, location, groups)
                if result:
                    report.consumers.append(consumer)
                    found = True
                elif result is None:
                    unknown = True
            if found:
                break
        if not found:
            (undetermined if unknown else uncovered).append(consumer)

    for report in reports:
        if report.consumers:
            report.status = Status.NEEDED
        elif report.entry.kind == Kind.PACKAGE_GROUP:
            # Without a resolved group, its coverage is unknown.
            if report.entry.label not in groups:
                report.status = Status.UNKNOWN
                report.reason = "unresolved package_group"
        elif report.entry.kind == Kind.PRIVATE:
            report.status = Status.UNKNOWN
            report.reason = "not a package"
    uncovered_references: list[str] = []
    for path in reference_files or []:
        if any(entry_covers_path(e, path, groups) for e in implicit_entries):
            continue
        results = [
            (r, entry_covers_path(r.entry, path, groups)) for r in reports
        ]
        if all(result is False for _, result in results):
            uncovered_references.append(path)
        for report, result in results:
            if result and report.status == Status.UNUSED:
                report.status = Status.UNVERIFIED
            if result and report.status == Status.UNVERIFIED:
                report.text_references.append(path)
    for report in reports:
        if report.status == Status.UNUSED and check_unused is not None:
            check = check_unused(report.entry)
            if check is not None:
                report.status, report.reason = check

    # Entries covered by implicit entries or other kept entries are redundant.
    for report in reports:
        if report.entry.kind == Kind.PRIVATE:
            continue
        for implicit in implicit_entries:
            if subsumes(implicit, report.entry):
                report.status = Status.REDUNDANT
                report.subsumed_by = "implicit visibility"
                break

    keep = (Status.NEEDED, Status.UNVERIFIED, Status.UNKNOWN)
    kept = [(i, r) for i, r in enumerate(reports) if r.status in keep]
    for index, report in enumerate(reports):
        if (
            report.entry.kind == Kind.PRIVATE
            or report.status == Status.REDUNDANT
        ):
            continue
        for other_index, other in kept:
            if other_index == index or not subsumes(other.entry, report.entry):
                continue
            # For duplicates, keep the first occurrence.
            if other.entry == report.entry and other_index > index:
                continue
            report.status = Status.REDUNDANT
            report.subsumed_by = other.text
            break
    return ListReport(reports, uncovered, undetermined, uncovered_references)


def sorted_labels(values: Iterable[str]) -> list[str]:
    """Sorts and dedups labels like buildifier: `//a:x` before `//a/b:x`."""
    return sorted(set(values), key=lambda v: v.split(":"))


def format_bazel_list(values: Sequence[str]) -> str:
    if not values:
        return 'visibility = ["//visibility:private"],'
    lines = ["visibility = ["]
    lines += [f'    "{v}",' for v in sorted_labels(values)]
    lines.append("],")
    return "\n".join(lines)


def format_gn_list(values: Sequence[str]) -> str:
    lines = ["visibility = ["]
    lines += [f'  "{v}",' for v in sorted_labels(values)]
    lines.append("]")
    return "\n".join(lines)


def format_bazel2gn_overwrite(values: Sequence[str]) -> str:
    quoted = ", ".join(f'"{v}"' for v in sorted_labels(values))
    return f"# {BAZEL2GN_ANNOTATION}raw_overwrite:[ {quoted} ]"


def gn_list_to_bazel(entries: Sequence[Entry], own_package: str) -> list[str]:
    """Converts GN entries to a minimal Bazel visibility list."""
    converted = {}
    for entry in entries:
        text = entry_to_bazel(entry, own_package)
        if text is not None:
            converted[text] = parse_bazel_entry(text, own_package)
    return sorted_labels(
        text
        for text, entry in converted.items()
        if not any(
            other != entry and subsumes(other, entry)
            for other in converted.values()
        )
    )


def expected_gn_entries(
    bazel_entries: Sequence[Entry], own_package: str
) -> set[Entry]:
    """The GN visibility bazel2gn generates, plus implicit own package."""
    result = set()
    for entry in bazel_entries:
        if entry.kind == Kind.PRIVATE:
            entry = Entry(Kind.PACKAGE, own_package)
        result.add(entry)
    result.add(Entry(Kind.PACKAGE, own_package))
    return result


