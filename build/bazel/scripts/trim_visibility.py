class Kind(enum.Enum):
    PUBLIC = "public"
    PRIVATE = "private"
    # All targets in `package`.
    PACKAGE = "package"
    # All targets in `package` and its subpackages.
    SUBPACKAGES = "subpackages"
    # A single target (GN only).
    TARGET = "target"
    # A Bazel package_group (Bazel only).
    PACKAGE_GROUP = "package_group"


@dataclasses.dataclass(frozen=True)
class Entry:
    """A visibility entry, independent of the Bazel or GN syntax used."""

    kind: Kind
    package: str = ""
    name: str = ""

    @property
    def label(self) -> Label:
        return Label(self.package, self.name)


PUBLIC = Entry(Kind.PUBLIC)
PRIVATE = Entry(Kind.PRIVATE)


def parse_bazel_entry(text: str, own_package: str) -> Entry:
    """Parses an entry of a Bazel `visibility` attribute."""
    if text == "//visibility:public":
        return PUBLIC
    if text == "//visibility:private":
        return PRIVATE
    label = parse_label(text, own_package)
    if label.name == "__pkg__":
        return Entry(Kind.PACKAGE, label.package)
    if label.name == "__subpackages__":
        return Entry(Kind.SUBPACKAGES, label.package)
    return Entry(Kind.PACKAGE_GROUP, label.package, label.name)


def parse_gn_entry(text: str, own_package: str) -> Entry:
    """Parses an entry of a GN `visibility` list (see `gn help visibility`)."""
    pattern = strip_toolchain(text.strip())
    if pattern == "*":
        return PUBLIC
    if pattern == "./*":
        return Entry(Kind.SUBPACKAGES, own_package)
    if pattern == ":*":
        return Entry(Kind.PACKAGE, own_package)
    if pattern.startswith("//") and pattern.endswith("/*"):
        return Entry(Kind.SUBPACKAGES, pattern[2:-2])
    if pattern == "//*":
        return Entry(Kind.SUBPACKAGES, "")
    if pattern.endswith(":*"):
        return Entry(Kind.PACKAGE, parse_label(pattern, own_package).package)
    label = parse_label(pattern, own_package)
    return Entry(Kind.TARGET, label.package, label.name)


def entry_to_bazel(entry: Entry, own_package: str) -> str | None:
    """Renders an entry in Bazel syntax.

    Returns None for entries that only cover the own package, since Bazel
    targets are always visible to their own package. GN single-target entries
    are widened to their package, because Bazel has no per-target visibility.
    """
    if entry.kind == Kind.PUBLIC:
        return "//visibility:public"
    if entry.kind == Kind.PRIVATE:
        return "//visibility:private"
    if entry.kind in (Kind.PACKAGE, Kind.TARGET):
        if entry.package == own_package:
            return None
        return f"//{entry.package}:__pkg__"
    if entry.kind == Kind.SUBPACKAGES:
        return f"//{entry.package}:__subpackages__"
    return str(entry.label)


def entry_to_gn(entry: Entry, own_package: str) -> str:
    """Renders an entry in GN syntax, matching bazel2gn's conversion."""
    if entry.kind == Kind.PUBLIC:
        return "*"
    if entry.kind == Kind.PRIVATE:
        return ":*"
    if entry.kind == Kind.PACKAGE:
        return ":*" if entry.package == own_package else f"//{entry.package}:*"
    if entry.kind == Kind.SUBPACKAGES:
        if entry.package == own_package:
            return "./*"
        return f"//{entry.package}/*" if entry.package else "//*"
    return str(entry.label)


def subsumes(outer: Entry, inner: Entry) -> bool:
    """Whether everything `inner` covers is also covered by `outer`."""
    if outer == inner:
        return True
    if inner.kind == Kind.PRIVATE:
        return False
    if outer.kind == Kind.PUBLIC:
        return True
    if inner.kind in (Kind.PUBLIC, Kind.PACKAGE_GROUP):
        return False
    if outer.kind == Kind.SUBPACKAGES:
        return is_in_package_tree(inner.package, outer.package)
    if outer.kind == Kind.PACKAGE:
        return inner.kind == Kind.TARGET and inner.package == outer.package
    return False


