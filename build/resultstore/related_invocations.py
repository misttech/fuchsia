"""ResultStore related invocations, hierarchy, and BES telemetry links."""

import dataclasses
import uuid
from collections.abc import Mapping

# Environment variable keys for related invocations.
ENV_PARENT_BUILD_ID = "RESULTSTORE_PARENT_BUILD_ID"
ENV_PARENT_BUILD_LINK = "RESULTSTORE_PARENT_BUILD_LINK"
ENV_SIBLING_BUILDS_LINK = "RESULTSTORE_SIBLING_BUILDS_LINK"

# Set by main_build.py (or inherited from developer environment).
ENV_FX_BUILD_UUID = "FX_BUILD_UUID"

# Propagated in infra environments (LUCI/Buildbucket) to tag ResultStore/BES uploads.
ENV_BUILDBUCKET_ID = "BUILDBUCKET_ID"

# Propagated in infra environments (LUCI/Buildbucket) to identify the builder.
ENV_BUILDBUCKET_BUILDER = "BUILDBUCKET_BUILDER"

# Exported by RsProfile in main_build.py or inherited from rs_profile configuration.
# Directly influences the rsproxy daemon to format ResultStore web links.
ENV_RESULTS_URL = "RS_results_url"

# Build Event Service (BES) metadata key constants.
KEY_FX_BUILD_UUID = "FX_BUILD_UUID"
KEY_BUILDBUCKET_ID = "BUILDBUCKET_ID"
KEY_BUILDBUCKET_BUILDER = "BUILDBUCKET_BUILDER"
KEY_PARENT_BUILD_ID = "PARENT_BUILD_ID"
KEY_PARENT_BUILD_LINK = "PARENT_BUILD_LINK"
KEY_SIBLING_BUILDS_LINK = "SIBLING_BUILDS_LINK"
KEY_SUB_BUILDS_LINK = "SUB_BUILDS_LINK"


def _bbid_link(bbid: str) -> str:
    """Formats the web URL for a Buildbucket ID (handling LED builds vs standard infra builds)."""
    if "/led/" in bbid:
        if not bbid.endswith("/+/build.proto"):
            return f"http://go/lucibuild/{bbid}/+/build.proto"
        return f"http://go/lucibuild/{bbid}"
    return f"http://go/bbid/{bbid}"


def _parent_build_link(results_url: str, parent_build_id: str) -> str:
    """Formats the direct web URL to a parent build in ResultStore."""
    return f"{results_url}/{parent_build_id}"


def _sub_builds_query_link(results_url: str, invocation_id: str) -> str:
    """Formats the query web URL that searches for sub-builds of this invocation."""
    return f"{results_url}/?q={KEY_PARENT_BUILD_ID}:{invocation_id}"


@dataclasses.dataclass(frozen=True)
class InvocationLinkage:
    """The resolved telemetry identity, child environment, and BES metadata for an invocation."""

    invocation_id: str
    child_env: dict[str, str]
    metadata: dict[str, str]


def resolve(
    env: Mapping[str, str],
    results_url: str = "",
    invocation_id: str | None = None,
) -> InvocationLinkage:
    """Resolves ResultStore invocation hierarchy, child environment, and BES metadata.

    This function is idempotent and sub-process safe: when passed a child environment
    generated by a parent invocation (containing RESULTSTORE_PARENT_BUILD_ID and
    RESULTSTORE_PARENT_BUILD_LINK), it correctly preserves the explicit hierarchy.
    """
    fx_build_uuid = env.get(ENV_FX_BUILD_UUID)
    bbid = env.get(ENV_BUILDBUCKET_ID)
    parent_id = env.get(ENV_PARENT_BUILD_ID)

    if invocation_id:
        resolved_id = invocation_id
    elif not parent_id and fx_build_uuid:
        # Top-level fx build: use FX_BUILD_UUID as the primary invocation id.
        resolved_id = fx_build_uuid
    else:
        resolved_id = str(uuid.uuid4())

    if not parent_id and bbid:
        # Top-level infra build: buildbucket is the parent ID
        parent_id = bbid

    effective_results_url = (
        results_url or env.get(ENV_RESULTS_URL, "")
    ).rstrip("/")

    explicit_parent_link = env.get(ENV_PARENT_BUILD_LINK)
    sibling_builds_link = env.get(ENV_SIBLING_BUILDS_LINK)

    # Compute sibling builds query link if not explicitly provided in the environment
    if not sibling_builds_link and effective_results_url:
        if bbid:
            sibling_builds_link = (
                f"{effective_results_url}/?q={KEY_BUILDBUCKET_ID}:{bbid}"
            )
        elif fx_build_uuid:
            sibling_builds_link = f"{effective_results_url}/?q={KEY_FX_BUILD_UUID}:{fx_build_uuid}"

    # Compute parent link
    parent_link: str | None = None
    if explicit_parent_link:
        parent_link = explicit_parent_link
    elif bbid and (not parent_id or parent_id == bbid):
        parent_link = _bbid_link(bbid)
    elif parent_id and effective_results_url:
        parent_link = _parent_build_link(effective_results_url, parent_id)

    # Compute sub-builds query link
    sub_builds_link: str | None = None
    if effective_results_url:
        sub_builds_link = _sub_builds_query_link(
            effective_results_url, resolved_id
        )

    # Construct child environment
    child_env: dict[str, str] = {
        ENV_PARENT_BUILD_ID: resolved_id,
    }
    if effective_results_url:
        child_env[ENV_RESULTS_URL] = effective_results_url
        child_env[ENV_PARENT_BUILD_LINK] = _parent_build_link(
            effective_results_url, resolved_id
        )
    if sub_builds_link:
        child_env[ENV_SIBLING_BUILDS_LINK] = sub_builds_link

    # Construct metadata
    metadata: dict[str, str] = {}
    if fx_build_uuid:
        metadata[KEY_FX_BUILD_UUID] = fx_build_uuid
    if bbid:
        metadata[KEY_BUILDBUCKET_ID] = bbid
    bb_builder = env.get(ENV_BUILDBUCKET_BUILDER)
    if bb_builder:
        metadata[KEY_BUILDBUCKET_BUILDER] = bb_builder
    if parent_id:
        metadata[KEY_PARENT_BUILD_ID] = parent_id
    if parent_link:
        metadata[KEY_PARENT_BUILD_LINK] = parent_link
    if sibling_builds_link:
        metadata[KEY_SIBLING_BUILDS_LINK] = sibling_builds_link
    if sub_builds_link:
        metadata[KEY_SUB_BUILDS_LINK] = sub_builds_link

    return InvocationLinkage(
        invocation_id=resolved_id,
        child_env=child_env,
        metadata=metadata,
    )
