package gn2gone

import (
	"bufio"
	"bytes"
	"path"
	"strings"

	"go.fuchsia.dev/fuchsia/build/tools/bazel2gn"
)

// Region says where in the tree a string literal or target is.
type Region string

const (
	// RegionExternal is a BUILD.gn file without the bazel2gn sentinel.
	RegionExternal Region = "external"
	// RegionAbove is above the sentinel in a sentinel BUILD.gn file.
	RegionAbove Region = "above"
	// RegionBelow is below the sentinel, i.e. generated by bazel2gn.
	RegionBelow Region = "below"
	// RegionGNI is a .gni file.
	RegionGNI Region = "gni"
	// RegionDotGN is the //.gn file.
	RegionDotGN Region = "dotgn"
)

// Target is a call that defines a target: `<template>("<name>") { ... }`,
// at any depth of `if`/`else` blocks, outside other targets.
type Target struct {
	File   string
	Line   int
	Region Region
	// Template is the called function, e.g. "group" or "rustc_library".
	Template string
	// Name is the literal target name, or "" if it's an expression.
	Name     string
	TestOnly bool
	// Attrs are the attributes assigned directly in the target's block.
	Attrs []string
	// InCondition is true if the target is inside an `if`/`else`.
	InCondition bool
	// Condition is the innermost enclosing condition as written, e.g.
	// "is_host", or "!(is_host)" in an `else` block; "" outside conditions.
	Condition string
	// OpaqueDeps is true if `deps` or `public_deps` is assigned anything
	// other than a list of string literals (e.g. a variable, or a list plus a
	// variable), so its entries can't all be inspected.
	OpaqueDeps bool
}

// HasAttr reports whether `attr` is assigned directly in the target's block.
func (t *Target) HasAttr(attr string) bool {
	for _, a := range t.Attrs {
		if a == attr {
			return true
		}
	}
	return false
}

// Literal is a string literal in a GN file.
type Literal struct {
	File   string
	Line   int
	Column int
	Region Region
	// Value is the string without surrounding quotes. Escapes are kept.
	Value string
	// Attr is the variable or attribute the string is assigned to, e.g.
	// "deps". For strings inside a scope literal (`foo = { bar = "x" }`), it
	// is the outer name ("foo") and InnerAttr is the inner one ("bar").
	Attr      string
	InnerAttr string
	// CallArgOf is the function name when the string is a call argument,
	// e.g. "import".
	CallArgOf string
	// Target is the enclosing target, or nil.
	Target *Target
	// InConcat is true if the string is an operand of `+`.
	InConcat bool
}

// FileIndex is what gn2gone extracts from one GN file.
type FileIndex struct {
	Path string
	// SentinelLine is the 1-based line of the bazel2gn sentinel, or 0.
	SentinelLine int
	Targets      []*Target
	Literals     []*Literal
	// AboveOther counts top-level statements above the sentinel that are not
	// `import()` or `assert()` calls or target definitions, e.g. variable
	// assignments or `if` blocks. Such statements mean BUILD.gn can't simply
	// be deleted.
	AboveOther int
}

// Dir returns the directory of the file, relative to the Fuchsia root.
func (fi *FileIndex) Dir() string { return path.Dir(fi.Path) }

// IsSentinelFile reports whether this is a BUILD.gn with the sentinel.
func (fi *FileIndex) IsSentinelFile() bool { return fi.SentinelLine > 0 }

var nonTargetFuncs = map[string]bool{
	"if": true, "foreach": true, "template": true, "declare_args": true, "set_defaults": true,
}

// FindSentinelLine returns the 1-based line of the bazel2gn sentinel in
// `content`, or 0 if there is none.
func FindSentinelLine(content []byte) int {
	if !bytes.Contains(content, []byte(bazel2gn.SentinelComment)) {
		return 0
	}
	s := bufio.NewScanner(bytes.NewReader(content))
	s.Buffer(make([]byte, 1024*1024), 16*1024*1024)
	for i := 1; s.Scan(); i++ {
		if strings.TrimSpace(s.Text()) == bazel2gn.SentinelComment {
			return i
		}
	}
	return 0
}

// IndexFile extracts targets and string literals from the parse tree of
// `relPath`. `sentinelLine` is the result of FindSentinelLine on its content.
func IndexFile(relPath string, sentinelLine int, tree *Node) *FileIndex {
	fi := &FileIndex{Path: relPath, SentinelLine: sentinelLine}
	kind := RegionExternal
	switch {
	case strings.HasSuffix(relPath, ".gni"):
		kind = RegionGNI
	case path.Base(relPath) == ".gn":
		kind = RegionDotGN
	}
	w := &walker{fi: fi, kind: kind}
	if tree == nil {
		return fi
	}
	// Top-level statements above the sentinel.
	if sentinelLine > 0 {
		for _, c := range tree.Child {
			if c.Line() >= sentinelLine {
				continue
			}
			switch {
			case c.Type == "BLOCK_COMMENT":
			case c.Type == "FUNCTION" && (c.Value == "import" || c.Value == "assert"):
			case c.Type == "FUNCTION" && !nonTargetFuncs[c.Value] && hasBlock(c):
			default:
				fi.AboveOther++
			}
		}
	}
	w.walk(tree, walkCtx{}, "", "")
	return fi
}

// isLiteralList reports whether `n` is a list containing only string
// literals.
func isLiteralList(n *Node) bool {
	if n.Type != "LIST" {
		return false
	}
	for _, c := range n.Child {
		if c.Type == "LITERAL" && strings.HasPrefix(c.Value, `"`) {
			continue
		}
		// gn's parse tree records comments inside lists as nodes too.
		if c.Type == "BLOCK_COMMENT" {
			continue
		}
		return false
	}
	return true
}

func hasBlock(n *Node) bool {
	for _, c := range n.Child {
		if c.Type == "BLOCK" {
			return true
		}
	}
	return false
}

type walker struct {
	fi   *FileIndex
	kind Region
}

func (w *walker) region(line int) Region {
	if w.kind != RegionExternal {
		return w.kind
	}
	if w.fi.SentinelLine > 0 {
		if line > w.fi.SentinelLine {
			return RegionBelow
		}
		return RegionAbove
	}
	return RegionExternal
}

type walkCtx struct {
	target      *Target
	attr, op    string
	inScope     bool
	scopeOwner  string
	callArgOf   string
	inCondition bool
	condition   string
}

func exprText(n *Node) string {
	if n == nil {
		return "?"
	}
	switch n.Type {
	case "LITERAL", "IDENTIFIER":
		return n.Value
	case "ACCESSOR":
		parts := []string{n.Value}
		for _, c := range n.Child {
			parts = append(parts, exprText(c))
		}
		return strings.Join(parts, ".")
	case "BINARY":
		var parts []string
		for _, c := range n.Child {
			parts = append(parts, exprText(c))
		}
		return strings.Join(parts, " "+n.Value+" ")
	case "FUNCTION":
		return n.Value + "(...)"
	}
	return n.Type
}

func (w *walker) walk(n *Node, ctx walkCtx, parentType, parentValue string) {
	switch n.Type {
	case "FUNCTION":
		var args, block *Node
		for _, c := range n.Child {
			switch c.Type {
			case "LIST":
				if args == nil {
					args = c
				}
			case "BLOCK":
				block = c
			}
		}
		nctx := ctx
		var newTarget *Target
		if block != nil && !nonTargetFuncs[n.Value] && ctx.target == nil {
			newTarget = &Target{
				File:        w.fi.Path,
				Line:        n.Line(),
				Region:      w.region(n.Line()),
				Template:    n.Value,
				InCondition: ctx.inCondition,
				Condition:   ctx.condition,
			}
			if args != nil && len(args.Child) > 0 && args.Child[0].Type == "LITERAL" {
				newTarget.Name = strings.Trim(args.Child[0].Value, `"`)
			}
			w.fi.Targets = append(w.fi.Targets, newTarget)
		}
		if args != nil {
			actx := nctx
			actx.callArgOf = n.Value
			w.walk(args, actx, "FUNCTION", n.Value)
		}
		if block != nil {
			bctx := nctx
			bctx.callArgOf = ""
			if newTarget != nil {
				bctx.target = newTarget
				bctx.attr = ""
				bctx.op = ""
				bctx.inScope = false
				bctx.scopeOwner = ""
			}
			w.walk(block, bctx, "FUNCTION", n.Value)
		}
		return
	case "CONDITION":
		// Children: the condition, the `if` block, and an optional `else`
		// block or nested `else if` CONDITION.
		nctx := ctx
		nctx.inCondition = true
		cond := ""
		for i, c := range n.Child {
			cctx := nctx
			switch i {
			case 0:
				cond = exprText(c)
			case 1:
				cctx.condition = cond
			default:
				cctx.condition = "!(" + cond + ")"
			}
			w.walk(c, cctx, "CONDITION", "")
		}
		return
	case "BINARY":
		if n.Value == "=" || n.Value == "+=" || n.Value == "-=" {
			lhs := ""
			if len(n.Child) > 0 {
				lhs = exprText(n.Child[0])
			}
			nctx := ctx
			if t := ctx.target; t != nil && ctx.attr == "" && !ctx.inScope {
				t.Attrs = append(t.Attrs, lhs)
				if lhs == "testonly" && len(n.Child) > 1 && n.Child[1].Value == "true" {
					t.TestOnly = true
				}
				if (lhs == "deps" || lhs == "public_deps") && len(n.Child) > 1 && !isLiteralList(n.Child[1]) {
					t.OpaqueDeps = true
				}
			}
			if ctx.attr == "" || ctx.inScope {
				nctx.attr = lhs
				nctx.op = n.Value
			}
			for _, c := range n.Child[min(1, len(n.Child)):] {
				w.walk(c, nctx, "BINARY", n.Value)
			}
			return
		}
	case "BLOCK":
		if parentType == "BINARY" {
			// Scope literal, e.g. `test_specs = { ... }`.
			nctx := ctx
			nctx.inScope = true
			nctx.scopeOwner = ctx.attr
			for _, c := range n.Child {
				w.walk(c, nctx, "BLOCK", "")
			}
			return
		}
	case "LITERAL":
		v := n.Value
		if len(v) >= 2 && v[0] == '"' {
			lit := &Literal{
				File:      w.fi.Path,
				Line:      n.Line(),
				Column:    n.Column(),
				Region:    w.region(n.Line()),
				Value:     v[1 : len(v)-1],
				Attr:      ctx.attr,
				CallArgOf: ctx.callArgOf,
				Target:    ctx.target,
				InConcat:  parentType == "BINARY" && parentValue == "+",
			}
			if ctx.inScope {
				lit.Attr = ctx.scopeOwner
				lit.InnerAttr = ctx.attr
			}
			w.fi.Literals = append(w.fi.Literals, lit)
		}
		return
	}
	for _, c := range n.Child {
		w.walk(c, ctx, n.Type, n.Value)
	}
}
