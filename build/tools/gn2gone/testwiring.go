// bazelRule is a top-level rule or macro call in a BUILD.bazel file.
type bazelRule struct {
	kind string
	// strings are all string literals in the call's arguments, except `name`.
	strings []string
	// tests is the `tests` attribute of a test_suite.
	tests    []string
	hasTests bool
	// allTests is true for a test_suite whose `tests` is missing or a literal
	// empty list and that has no `tags` filter, which in Bazel means every
	// non-manual test in the package.
	allTests bool
	hasTags  bool
	// manual is true if the rule's `tags` contain "manual", which excludes it
	// from a test_suite's implicit "every test in the package".
	manual bool
}

type bazelPackage struct {
	rules map[string]*bazelRule
}

// TestWiring answers whether a Bazel test target is run by CQ through a
// `bazel_test_suite()` in GN.
//
// Bazel tests reach CQ through GN `bazel_test_suite()` targets, whose
// `host_tests` and `target_tests` list Bazel labels. From those seeds,
// TestWiring follows `test_suite(tests = [...])` across packages, and within
// a package follows every string that names another target in the same
// package (e.g. `wrap_host_rust_test(binary_name = "foo_test")` or
// `fx_unittest_package(unit_tests = [":foo_test"])`).
//
// This is deliberately approximate: following same-package strings can mark
// a target as reached when a reached rule only builds it (e.g. `data`), so a
// test named that way counts as wired even if no `bazel test` runs it. Also,
// in a package with an implicit "every test" test_suite, a GN test name with
// no top-level Bazel rule (e.g. one generated by a macro) counts as wired.
type TestWiring struct {
	root     string
	packages map[string]*bazelPackage
	// reached and allReached are indexed by mode: host (from `host_tests`)
	// and target (from `target_tests`). They are tracked separately because
	// a test run on device doesn't run on host, and a host test listed in
	// `target_tests` is silently dropped by the Bazel test runner.
	reached [2]map[string]map[string]bool
	// allReached holds packages with a `test_suite` whose `tests` is missing
	// or a literal empty list and has no `tags` filter, which in Bazel means
	// every test in the package that isn't tagged "manual".
	allReached [2]map[string]bool
}

const (
	modeHost   = 0
	modeTarget = 1
)

var bareNameRE = regexp.MustCompile(`^[A-Za-z0-9_.+\-]+$`)

// NewTestWiring computes reachability from the `host_tests` and
// `target_tests` attributes of every `bazel_test_suite()` in `files`.
func NewTestWiring(root string, files []*FileIndex) *TestWiring {
	w := &TestWiring{
		root:       root,
		packages:   map[string]*bazelPackage{},
		reached:    [2]map[string]map[string]bool{{}, {}},
		allReached: [2]map[string]bool{{}, {}},
	}
	type item struct {
		label string
		mode  int
	}
	var queue []item
	for _, fi := range files {
		for _, l := range fi.Literals {
			if l.Target == nil || l.Target.Template != "bazel_test_suite" {
				continue
			}
			if l.Attr != "host_tests" && l.Attr != "target_tests" {
				continue
			}
			mode := modeHost
			if l.Attr == "target_tests" {
				mode = modeTarget
			}
			if label, ok := absLabel(stripToolchain(l.Value), path.Dir(l.File)); ok {
				queue = append(queue, item{label, mode})
			}
		}
	}
	seen := map[item]bool{}
	for len(queue) > 0 {
		it := queue[0]
		queue = queue[1:]
		if seen[it] {
			continue
		}
		seen[it] = true
		label, mode := it.label, it.mode
		reached := w.reached[mode]
		pkg, name, _ := strings.Cut(label[2:], ":")
		if reached[pkg] == nil {
			reached[pkg] = map[string]bool{}
		}
		reached[pkg][name] = true
		p := w.pkg(pkg)
		rule := p.rules[name]
		if rule == nil {
			continue
		}
		if rule.kind == "test_suite" {
			// A non-literal `tests` (e.g. a variable) with no strings reaches
			// nothing: assuming "all tests" could drop a test silently.
			if rule.allTests {
				w.allReached[mode][pkg] = true
			}
			for _, t := range rule.tests {
				if l, ok := absLabel(t, pkg); ok {
					queue = append(queue, item{l, mode})
				}
			}
			continue
		}
		for _, s := range rule.strings {
			var n string
			switch {
			case strings.HasPrefix(s, ":"):
				n = s[1:]
			case strings.HasPrefix(s, "//"+pkg+":"):
				n = s[len(pkg)+3:]
			case bareNameRE.MatchString(s):
				n = s
			default:
				continue
			}
			if p.rules[n] != nil {
				queue = append(queue, item{"//" + pkg + ":" + n, mode})
			} else if strings.HasPrefix(s, ":") || strings.HasPrefix(s, "//") || strings.HasSuffix(n, "_test") || strings.HasSuffix(n, "_tests") {
				// Implicit targets, e.g. `<name>_test` from `with_unit_tests`.
				reached[pkg][n] = true
			}
		}
	}
	return w
}

// Wired reports whether the Bazel target `//pkg:name` is reachable from the
// `host_tests` (if `host`) or `target_tests` of a `bazel_test_suite()`.
func (w *TestWiring) Wired(pkg, name string, host bool) bool {
	mode := modeTarget
	if host {
		mode = modeHost
	}
	if w.reached[mode][pkg][name] {
		return true
	}
	if !w.allReached[mode][pkg] {
		return false
	}
	rule := w.pkg(pkg).rules[name]
	return rule == nil || !rule.manual
}

func (w *TestWiring) pkg(pkg string) *bazelPackage {
	if p, ok := w.packages[pkg]; ok {
		return p
	}
	p := &bazelPackage{rules: map[string]*bazelRule{}}
	w.packages[pkg] = p
	file := filepath.Join(w.root, pkg, "BUILD.bazel")
	content, err := os.ReadFile(file)
	if err != nil {
		return p
	}
	f, err := bazel2gn.ParseBytes(file, content)
	if err != nil {
		return p
	}
	for _, stmt := range f.Stmts {
		es, ok := stmt.(*syntax.ExprStmt)
		if !ok {
			continue
		}
		call, ok := es.X.(*syntax.CallExpr)
		if !ok {
			continue
		}
		fn, ok := call.Fn.(*syntax.Ident)
		if !ok {
			continue
		}
		rule := &bazelRule{kind: fn.Name}
		name := ""
		for _, arg := range call.Args {
			bin, ok := arg.(*syntax.BinaryExpr)
			if !ok || bin.Op != syntax.EQ {
				continue
			}
			key, ok := bin.X.(*syntax.Ident)
			if !ok {
				continue
			}
			strs := stringLiterals(bin.Y)
			switch key.Name {
			case "name":
				if len(strs) == 1 {
					name = strs[0]
				}
				continue
			case "tests":
				rule.tests = strs
				rule.hasTests = true
				if list, ok := bin.Y.(*syntax.ListExpr); ok && len(list.List) == 0 {
					rule.allTests = true
				}
			case "tags":
				rule.hasTags = true
				for _, t := range strs {
					if t == "manual" {
						rule.manual = true
					}
				}
			}
			rule.strings = append(rule.strings, strs...)
		}
		if name != "" {
			if rule.kind == "test_suite" && !rule.hasTests {
				rule.allTests = true
			}
			// A `tags` filter selects a subset that isn't modeled here.
			if rule.hasTags {
				rule.allTests = false
			}
			p.rules[name] = rule
		}
	}
	return p
}

func stringLiterals(e syntax.Expr) []string {
	var out []string
	syntax.Walk(e, func(n syntax.Node) bool {
		if lit, ok := n.(*syntax.Literal); ok && lit.Token == syntax.STRING {
			if s, ok := lit.Value.(string); ok {
				out = append(out, s)
			}
		}
		return true
	})
	return out
}

// absLabel turns a GN or Bazel label into "//pkg:name", relative to `dir`.
func absLabel(s, dir string) (string, bool) {
	if s == "" || strings.ContainsAny(s, "$ ") {
		return "", false
	}
	var pkg, name string
	switch {
	case strings.HasPrefix(s, "//"):
		var hasColon bool
		pkg, name, hasColon = strings.Cut(s[2:], ":")
		if !hasColon {
			name = path.Base(pkg)
		}
	case strings.HasPrefix(s, ":"):
		pkg, name = dir, s[1:]
	default:
		d, n, hasColon := strings.Cut(s, ":")
		pkg = path.Clean(path.Join(dir, d))
		name = n
		if !hasColon {
			name = path.Base(pkg)
		}
	}
	pkg = strings.TrimSuffix(pkg, "/")
	if name == "" {
		return "", false
	}
	return "//" + pkg + ":" + name, true
}
