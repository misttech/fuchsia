var (
	gnBin         = flag.String("gn_bin", "", "Path to the GN binary.")
	buildifierBin = flag.String("buildifier_bin", "", "Path to the buildifier binary.")
	checkOnly     = flag.Bool("check_only", false, "When true, compare generated GN content with existing BUILD.gn files without writing to them.")
	jsonOutput    = flag.Bool("json", false, "When true, print a JSON list of per-directory errors to stdout instead of logging them.")

	directoryList = flag.String("directory_list", "", "Path to a file containing a list of directories to sync, directory paths are relative to --fuchsia_dir.")
	fuchsiaDir    = flag.String("fuchsia_dir", "", "Path to the Fuchsia root directory.")
	workers       = flag.Int("workers", runtime.NumCPU(), "Number of parallel workers. Defaults to runtime.NumCPU().")
)

// commonFileHeader is the header to add to the top of every BUILD.gn file
// converted from a BUILD.bazel file.
const (
	bazel2gnComment = `#
#  ________  _________  ________  ________
# |\   ____\|\___   ___\\   __  \|\   __  \
# \ \  \___|\|___ \  \_\ \  \|\  \ \  \|\  \
#  \ \_____  \   \ \  \ \ \  \\\  \ \   ____\
#   \|____|\  \   \ \  \ \ \  \\\  \ \  \___|
#     ____\_\  \   \ \__\ \ \_______\ \__\
#    |\_________\   \|__|  \|_______|\|__|
#    \|_________|
#
#
# AUTO-GENERATED - DO NOT EDIT
#
# The targets below are auto-generated based on the targets defined in the
# BUILD.bazel file from the same directory. If you made changes to targets in
# Bazel, instead of editing this file manually, run:
#
#   > fx bazel2gn
#
# Please do NOT edit this file directly. Instead, edit the BUILD.bazel file and
# rerun bazel2gn.

import("//build/tools/bazel2gn/bazel_migration.gni")
`

	// LINT.IfChange(bazel2gn_output)
	sentinelComment = "## BAZEL2GN SENTINEL - DO NOT EDIT BELOW THIS LINE ##"
	// LINT.ThenChange(//scripts/shac/bazel_migration.star:bazel2gn_output)
)

func main() {
	flag.Parse()
	logOut := io.Writer(os.Stdout)
	if *jsonOutput {
		// Keep stdout parseable as JSON.
		logOut = os.Stderr
	}
	log := logger.NewLogger(logger.InfoLevel, color.NewColor(color.ColorAuto), logOut, os.Stderr, "[bazel2gn] ")

	if *gnBin == "" {
		log.Fatalf("--gn_bin is required, see --help")
	}

	if *buildifierBin == "" {
		log.Fatalf("--buildifier_bin is required, see --help")
	}

	if *fuchsiaDir == "" {
		log.Fatalf("--fuchsia_dir is required, see --help")
	}

	// If --directory_list is not set, the directories to sync are discovered by
	// searching --fuchsia_dir for BUILD.gn files containing the bazel2gn
	// sentinel.
	var dirs []string
	var err error
	if *directoryList != "" {
		dirs, err = readDirectoryList(*directoryList)
	} else {
		dirs, err = discoverSentinelDirectories(*fuchsiaDir)
	}
	if err != nil {
		log.Fatalf("%v", err)
	}

	commonParams := syncParams{
		buildifierBin: *buildifierBin,
		gnBin:         *gnBin,
		checkOnly:     *checkOnly,
		log:           log,
	}

	errs := runBatch(context.Background(), dirs, *fuchsiaDir, *workers, commonParams)
	if *jsonOutput {
		if err := writeDiagnostics(os.Stdout, *fuchsiaDir, errs); err != nil {
			log.Fatalf("%v", err)
		}
		if len(errs) > 0 {
			os.Exit(1)
		}
		return
	}
	if len(errs) > 0 {
		var sb strings.Builder
		sb.WriteString("syncing in batch mode:\n")
		for _, e := range errs {
			fmt.Fprintf(&sb, "* syncing directory %s: %v\n", e.dir, e.err)
		}
		log.Fatalf("%s", sb.String())
	}
}

// dirError pairs a directory with the error from syncing it. It's a record
// that runBatch collects for each failed directory, not an error itself:
// nothing returns it as an `error`, and keeping the directory separate lets
// callers report it without parsing it back out of a message.
//
// err may wrap a *bazel2gn.FileError or *outOfSyncError, which toDiagnostic
// uses to say which file and line in the directory the error applies to.
type dirError struct {
	// dir is the directory relative to --fuchsia_dir, or as given if it's
	// not inside --fuchsia_dir.
	dir string
	err error
}

// outOfSyncError means that BUILD.gn doesn't match what bazel2gn generates
// from BUILD.bazel.
type outOfSyncError struct {
	bazelPath string
	gnPath    string
	relDir    string
	// diff is the diff of GN targets (-actual, +expected).
	diff string
}

func (e *outOfSyncError) Error() string {
	return fmt.Sprintf(`BUILD.gn is out of sync with BUILD.bazel
The following BUILD files are not in sync:

  - %s
  - %s

Make sure you update the BUILD.bazel file, then run this command to sync BUILD.gn:

  fx bazel2gn -d %s

Diff of GN targets (-actual, +expected):

%s`, e.bazelPath, e.gnPath, e.relDir, e.diff)
}

// LINT.IfChange(bazel2gn_json)

// diagnostic is the JSON representation of a dirError, printed with --json.
type diagnostic struct {
	// Directory is the directory relative to --fuchsia_dir.
	Directory string `json:"directory"`
	// File is the path relative to --fuchsia_dir of the file that the error
	// applies to, or empty if it doesn't apply to a specific file.
	File string `json:"file,omitempty"`
	// Line is the 1-based line within File, or 0 for the whole file.
	Line int `json:"line,omitempty"`
	// OutOfSync is true if BUILD.gn is out of sync with BUILD.bazel, in which
	// case Message is the diff of GN targets (-actual, +expected).
	OutOfSync bool   `json:"out_of_sync,omitempty"`
	Message   string `json:"message"`
}

// LINT.ThenChange(//scripts/shac/bazel_migration.star:bazel2gn_json)

func toDiagnostic(fuchsiaDir string, e dirError) diagnostic {
	d := diagnostic{Directory: e.dir, Message: e.err.Error()}
	var outOfSync *outOfSyncError
	var fileErr *bazel2gn.FileError
	if errors.As(e.err, &outOfSync) {
		d.File = filepath.Join(e.dir, "BUILD.gn")
		d.OutOfSync = true
		d.Message = outOfSync.diff
	} else if errors.As(e.err, &fileErr) {
		if rel, err := filepath.Rel(fuchsiaDir, fileErr.Path); err == nil && filepath.IsLocal(rel) {
			d.File = rel
			d.Line = fileErr.Line
			d.Message = fileErr.Err.Error()
		}
	}
	return d
}

// writeDiagnostics writes `errs` as a JSON list of diagnostics to `w`.
func writeDiagnostics(w io.Writer, fuchsiaDir string, errs []dirError) error {
	// Not a nil slice, which would be encoded as null rather than [].
	diags := []diagnostic{}
	for _, e := range errs {
		diags = append(diags, toDiagnostic(fuchsiaDir, e))
	}
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	return enc.Encode(diags)
}

type syncParams struct {
	// relDir is the directory relative to the Fuchsia root, used to suggest a
	// fix command in check-only mode.
	relDir string

	buildifierBin string
	gnBin         string
	checkOnly     bool
	log           *logger.Logger
}

func syncDirectory(ctx context.Context, bazelInputPath string, gnOutputPath string, p syncParams) error {
	// Format the input BUILD.bazel file first to ensure consistent output.
	//
	// For example, buildifier can reorder attributes of targets in BUILD.bazel,
	// resulting in different BUILD.gn outputs since `gn format` doesn't care
	// about field order.
	//
	// Formatting happens in memory. The formatted content is only written back
	// when not in check-only mode, so --check_only never modifies the source
	// tree (e.g. shac mounts the repository read-only).
	original, formatted, err := formatBazelFile(ctx, p.buildifierBin, bazelInputPath)
	if errors.Is(err, fs.ErrNotExist) {
		return &bazel2gn.FileError{Path: gnOutputPath, Err: errors.New("BUILD.gn has the bazel2gn sentinel but there's no BUILD.bazel next to it")}
	} else if err != nil {
		return err
	}
	if !p.checkOnly && !bytes.Equal(original, formatted) {
		if err := os.WriteFile(bazelInputPath, formatted, 0644); err != nil {
			return fmt.Errorf("writing formatted %s: %v", bazelInputPath, err)
		}
	}

	bazelIn, err := bazel2gn.ParseBytes(bazelInputPath, formatted)
	if err != nil {
		return &bazel2gn.FileError{Path: bazelInputPath, Err: fmt.Errorf("parsing: %w", err)}
	}

	finalLines, err := bazel2gn.FileToGN(bazelIn)
	if err != nil {
		var fileErr *bazel2gn.FileError
		if !errors.As(err, &fileErr) {
			return &bazel2gn.FileError{Path: bazelInputPath, Err: fmt.Errorf("converting to GN: %v", err)}
		}
		// Line numbers refer to the formatted content, so they're only
		// meaningful for the file on disk if it's already formatted.
		if !bytes.Equal(original, formatted) {
			fileErr.Line = 0
		}
		return fileErr
	}

	// Open the GN build file with readonly first, to read the GN targets that
	// need to be preserved.
	gnOut, err := os.Open(gnOutputPath)
	if err != nil {
		return fmt.Errorf("opening %s for reading: %v", gnOutputPath, err)
	}
	toPreserve, err := gnTargetsToPreserve(gnOut)
	gnOut.Close()
	if err != nil {
		return fmt.Errorf("reading GN targets to preserve from %s: %v", gnOutputPath, err)
	}

	finalContent, err := gnFormatted(
		ctx,
		p.gnBin,
		toPreserve+"\n"+sentinelComment+"\n"+bazel2gnComment+"\n"+strings.Join(finalLines, "\n"),
	)
	if err != nil {
		return &bazel2gn.FileError{Path: gnOutputPath, Err: fmt.Errorf("formatting GN targets: %v", err)}
	}

	gnOut, err = os.Open(gnOutputPath)
	if err != nil {
		return fmt.Errorf("opening %s for reading actual content: %v", gnOutputPath, err)
	}
	actual, err := io.ReadAll(gnOut)
	gnOut.Close()
	if err != nil {
		return fmt.Errorf("reading actual content of %s: %v", gnOutputPath, err)
	}

	diff := cmp.Diff(string(actual), finalContent)

	if p.checkOnly {
		if diff != "" {
			return &outOfSyncError{bazelPath: bazelInputPath, gnPath: gnOutputPath, relDir: p.relDir, diff: diff}
		}
	} else {
		// Avoid touching BUILD.gn when no changes are made, which can trigger unnecessary `gn gen`s.
		if diff == "" {
			return nil
		}
		// Open the GN file again for write.
		gnOut, err = os.OpenFile(gnOutputPath, os.O_WRONLY|os.O_TRUNC, 0)
		if err != nil {
			return fmt.Errorf("opening %s for writing: %v", gnOutputPath, err)
		}
		defer gnOut.Close()
		if _, err := io.WriteString(gnOut, finalContent); err != nil {
			return fmt.Errorf("writing final GN build file to %s: %v", gnOutputPath, err)
		}
	}
	return nil
}

// readDirectoryList reads a text file with one directory path per line.
func readDirectoryList(directoryList string) ([]string, error) {
	var dirs []string
	f, err := os.Open(directoryList)
	if err != nil {
		return nil, fmt.Errorf("opening directory list file %s: %v", directoryList, err)
	}
	defer f.Close()
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line != "" { // Ignore empty lines.
			dirs = append(dirs, line)
		}
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("reading directory list file %s: %v", directoryList, err)
	}
	if len(dirs) == 0 {
		return nil, fmt.Errorf("no directories found in directory list file %s", directoryList)
	}
	return dirs, nil
}

// discoverSentinelDirectories walks `fuchsiaDir` to find all directories
// whose BUILD.gn files contain the bazel2gn sentinel comment, including those
// in nested repositories such as vendor/google. Returned paths are relative to
// `fuchsiaDir`.
//
// Symlinks are not followed, and directories matched by skipDiscovery are
// skipped.
func discoverSentinelDirectories(fuchsiaDir string) ([]string, error) {
	var dirs []string
	err := filepath.WalkDir(fuchsiaDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			rel, err := filepath.Rel(fuchsiaDir, path)
			if err != nil {
				return err
			}
			if skipDiscovery(rel) {
				return filepath.SkipDir
			}
			return nil
		}
		if d.Name() != "BUILD.gn" || !d.Type().IsRegular() {
			return nil
		}
		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.Contains(content, []byte(sentinelComment)) {
			rel, err := filepath.Rel(fuchsiaDir, filepath.Dir(path))
			if err != nil {
				return err
			}
			dirs = append(dirs, rel)
		}
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("discovering bazel2gn sentinel directories in %s: %v", fuchsiaDir, err)
	}
	if len(dirs) == 0 {
		return nil, fmt.Errorf("no BUILD.gn files containing the bazel2gn sentinel found in %s", fuchsiaDir)
	}
	return dirs, nil
}

// skipDiscovery returns whether to skip the directory `rel`, relative to the
// Fuchsia root directory, when discovering bazel2gn-managed directories. These
// are large directories known to not contain any.
func skipDiscovery(rel string) bool {
	switch rel {
	case "out", "prebuilt", "third_party/golibs/vendor", "third_party/rust_crates/vendor":
		return true
	}
	return filepath.Base(rel) == ".git"
}

// runBatch runs syncDirectory in parallel over a list of directories `dirs`,
// with paths relative to `fuchsiaDir`. Absolute paths must be inside
// `fuchsiaDir`. It returns the errors sorted by directory.
// `workers` controls the maximum number of goroutines to run in parallel.
func runBatch(ctx context.Context, dirs []string, fuchsiaDir string, workers int, p syncParams) []dirError {
	sem := make(chan struct{}, workers)
	errChan := make(chan dirError, len(dirs))
	for _, dir := range dirs {
		sem <- struct{}{}
		go func(d string) {
			defer func() { <-sem }()

			relDir := filepath.Clean(d)
			if filepath.IsAbs(d) {
				var err error
				relDir, err = filepath.Rel(fuchsiaDir, d)
				if err != nil || !filepath.IsLocal(relDir) {
					errChan <- dirError{d, fmt.Errorf("directory is not inside --fuchsia_dir %s", fuchsiaDir)}
					return
				}
			}

			absDir := filepath.Join(fuchsiaDir, relDir)
			bazelInput := filepath.Join(absDir, "BUILD.bazel")
			gnOutput := filepath.Join(absDir, "BUILD.gn")
			dirParams := p
			dirParams.relDir = relDir
			err := syncDirectory(ctx, bazelInput, gnOutput, dirParams)
			if err == nil {
				return
			}
			errChan <- dirError{relDir, err}
		}(dir)
	}
	for i := 0; i < workers; i++ {
		sem <- struct{}{}
	}
	close(sem)
	close(errChan)

	var errs []dirError
	for e := range errChan {
		errs = append(errs, e)
	}
	slices.SortFunc(errs, func(a, b dirError) int { return strings.Compare(a.dir, b.dir) })
	return errs
}

func gnTargetsToPreserve(r io.Reader) (string, error) {
	s := bufio.NewScanner(r)
	ret := strings.Builder{}
	for s.Scan() {
		line := s.Text()
		if strings.TrimSpace(line) == sentinelComment {
			break
		}
		if _, err := ret.WriteString(line + "\n"); err != nil {
			return "", fmt.Errorf("writing existing line to string buffer: %v", err)
		}
	}
	return ret.String(), nil
}

// gnFormatted formats the given GN targets using `gn format --stdin`.
func gnFormatted(ctx context.Context, gnBin string, original string) (string, error) {
	cmd := exec.CommandContext(ctx, gnBin, "format", "--stdin")
	cmd.Stdin = strings.NewReader(original)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("`gn format` failed (%v): %s", err, strings.TrimSpace(string(out)))
	}
	return string(out), nil
}

var buildifierErrorRE = regexp.MustCompile(`(?m)^<stdin>:(\d+):\d+: (.*)`)

// formatBazelFile formats the given Bazel file in memory by piping its content
// through `buildifier -mode=fix -type=build`, without modifying the file on
// disk. It returns both the original and the formatted content.
func formatBazelFile(ctx context.Context, buildifierBin string, path string) ([]byte, []byte, error) {
	content, err := os.ReadFile(path)
	if err != nil {
		return nil, nil, fmt.Errorf("reading %s: %w", path, err)
	}
	cmd := exec.CommandContext(ctx, buildifierBin, "-mode=fix", "-type=build")
	cmd.Stdin = bytes.NewReader(content)
	var stderr strings.Builder
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		fileErr := &bazel2gn.FileError{Path: path, Err: fmt.Errorf("`buildifier` failed (%v): %s", err, strings.TrimSpace(stderr.String()))}
		// buildifier reports syntax errors as "<stdin>:<line>:<col>: <msg>".
		if m := buildifierErrorRE.FindStringSubmatch(stderr.String()); m != nil {
			fileErr.Line, _ = strconv.Atoi(m[1])
			fileErr.Err = errors.New(m[2])
		}
		return nil, nil, fileErr
	}
	return content, out, nil
}
